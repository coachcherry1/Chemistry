/* tools/answer-key.js: writes the answer key as Markdown.
 *
 *   node tools/answer-key.js > ANSWER_KEY.md
 *
 * Everything comes from the data, the model (chem.js) and the item bank, so
 * the key cannot drift from what the activity marks right.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const src = path.join(__dirname, '..', 'src');
const ctx = {
  console, Math, JSON, Object, Array, String, Number, Error, isNaN, parseInt, Date, RegExp, URLSearchParams,
  window: { matchMedia: () => ({ matches: false }), addEventListener() {} },
  document: { addEventListener() {}, documentElement: {} },
  getComputedStyle: () => ({ getPropertyValue: () => '' })
};
vm.createContext(ctx);
const html = fs.readFileSync(path.join(src, 'index.html'), 'utf8');
[...html.matchAll(/<script src="([^"]+)"><\/script>/g)].forEach((m) => {
  vm.runInContext(fs.readFileSync(path.join(src, m[1]), 'utf8'), ctx, { filename: m[1] });
});
const { SUBSTANCES, Chem, QUIZZES, App } = ctx;
const sub = (id) => Chem.sub(id);

const out = [];
const p = (s) => out.push(s == null ? '' : s);

p('# Intermolecular Forces, answer key');
p();
p('Generated by `node tools/answer-key.js` from the data, the model and the item bank. Do not edit by hand.');
p();
p(`${App.STEPS.length} steps; ${App.GRADED} graded questions per attempt. ★ marks a core question, asked in every attempt; ` +
  'the rest of each checkpoint is drawn at random from its pool. In the LMS, choice letters are recorded as ' +
  'a = the correct answer below, b, c, d = the others in the order listed (the screen shuffles them).');
p();
p('## Substances');
p();
p('Melting and boiling points at 1 atm, CRC Handbook of Chemistry and Physics (97th ed.). Hydrogen bonds per molecule = the smaller of ' +
  '(H atoms on N, O or F) and (lone pairs on N, O or F).');
p();
p('| Substance | Formula | Electrons | Polar? | Strongest force | H on N/O/F | Lone pairs on N/O/F | H-bonds per molecule | Melts | Boils |');
p('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
Object.keys(SUBSTANCES).forEach((id) => {
  const x = sub(id);
  p(`| ${x.name} | ${x.text} | ${x.electrons} | ${x.polar ? 'polar' : 'nonpolar'} | ${Chem.IMF_SHORT[x.imf]} | ${x.donors.length} | ` +
    `${x.receivers.length} | ${x.pairs} | ${x.mp == null ? 'never, at 1 atm' : Chem.fmtT(x.mp)} | ${Chem.fmtT(x.bp)} |`);
});
p();
p('## Steps, races and predictions (not graded)');
p();
App.STEPS.forEach((s, k) => {
  p(`${k + 1}. **${s.title}** (\`${s.id}\`)`);
  if (s.assign || ['phases', 'count', 'rank'].indexOf(s.kind) >= 0) {
    p(`   - Name the IMFs first: ${s.ids.map((id) => sub(id).text + ' ' + Chem.forcesText(id)).join('; ')}.`);
  }
  if (s.predict && App.PREDICT[s.predict]) {
    const pr = App.predictionFor(s.predict, s.ids || []);
    p(`   - Predict: ${pr.q} **${pr.choices[pr.answer]}**`);
  }
  if (s.ids && s.ids.length > 1 && s.kind !== 'cloud') p(`   - ${App.raceStory(s.ids) || ''}`);
  if (s.kind === 'phases') p(`   - At 25 °C: ${s.ids.map((id) => sub(id).text + ' ' + Chem.phaseAt(id, s.K)).join(', ')}.`);
  if (s.kind === 'draw') s.tasks.forEach((t) => p(`   - ${t.text} Donor: an H on O of ${t.donor.map((m) => s.mols[m].name).join(' or ')}; ` +
    `receiver: a lone pair on O of ${t.receiver.map((m) => s.mols[m].name).join(' or ')}.`));
  if (s.kind === 'whichH') p(`   - Donors: ${s.mols.map((m) => sub(m.id).name + ' ' + sub(m.id).donors.length).join(', ')}.`);
  if (s.kind === 'count') p(`   - ${s.ids.map((id) => sub(id).name + ': ' + sub(id).donors.length + ' H, ' + sub(id).receivers.length +
    ' lone pairs, ' + sub(id).pairs + ' hydrogen bonds').join('; ')}.`);
});
p();
Object.keys(QUIZZES).forEach((k) => {
  const Q = QUIZZES[k];
  p(`## ${Q.title}`);
  p();
  p(`${Q.draw} questions per attempt from a pool of ${Q.pool.length}.`);
  p();
  Q.pool.forEach((q, n) => {
    p(`${n + 1}. ${Q.core.indexOf(q.id) >= 0 ? '★ ' : ''}\`${q.id}\`: ${q.q}`);
    p(`   - **Answer:** ${q.choices[0]}`);
    p(`   - Others: ${q.choices.slice(1).join('; ')}`);
    p(`   - Why: ${q.why}`);
  });
  p();
});
process.stdout.write(out.join('\n'));

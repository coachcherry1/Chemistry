/* tools/answer-key.js: writes the answer key as Markdown.
 *
 *   node tools/answer-key.js > ANSWER_KEY.md
 *
 * Everything comes from the data, the model (chem.js) and the item bank, so
 * the key cannot drift from what the activity marks right.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const src = path.join(__dirname, '..', 'src');
const ctx = {
  console, Math, JSON, Object, Array, String, Number, Error, isNaN, parseInt, Date, RegExp, URLSearchParams,
  window: { matchMedia: () => ({ matches: false }), addEventListener() {} },
  document: { addEventListener() {}, documentElement: {} },
  getComputedStyle: () => ({ getPropertyValue: () => '' })
};
vm.createContext(ctx);
const html = fs.readFileSync(path.join(src, 'index.html'), 'utf8');
[...html.matchAll(/<script src="([^"]+)"><\/script>/g)].forEach((m) => {
  vm.runInContext(fs.readFileSync(path.join(src, m[1]), 'utf8'), ctx, { filename: m[1] });
});
const { SUBSTANCES, Chem, QUIZZES, App } = ctx;
const sub = (id) => Chem.sub(id);

const out = [];
const p = (s) => out.push(s == null ? '' : s);

p('# Properties of Liquids, answer key');
p();
p('Generated by `node tools/answer-key.js` from the data, the model and the item bank. Do not edit by hand.');
p();
p(`${App.STEPS.length} steps; ${App.GRADED} graded questions per attempt. ★ marks a core question, asked in every attempt; ` +
  'the rest of each checkpoint is drawn at random from its pool. In the LMS, choice letters are recorded as ' +
  'a = the correct answer below, b, c, d = the others in the order listed (the screen shuffles them).');
p();
p('## The liquids');
p();
p('At the same temperature, the class rule: stronger IMFs, higher surface tension, higher viscosity, slower evaporation. ' +
  'Students never see these numbers; the validator only lets a comparison be asked when the rule and these 20 °C values agree ' +
  'by a clear margin (surface tension 5%, viscosity 30%, vapour pressure 50%). 2-Butanone and 1-butanol have the same surface ' +
  'tension, so that pair is never compared by surface tension.');
p();
p('| Liquid | Formula | Electrons | Strongest force | H-bonds per molecule | Surface tension (mN/m) | Viscosity (mPa·s) | Vapour pressure (kPa) |');
p('| --- | --- | --- | --- | --- | --- | --- | --- |');
Object.keys(ctx.LIQUID).forEach((id) => {
  const x = sub(id), L = ctx.LIQUID[id];
  p(`| ${x.name} | ${x.text} | ${x.electrons} | ${Chem.IMF_SHORT[x.imf]} | ${x.pairs} | ${L.st} | ${L.visc} | ${L.vp} |`);
});
p();
p('## Steps and predictions (not graded)');
p();
App.STEPS.forEach((s, k) => {
  p(`${k + 1}. **${s.title}** (\`${s.id}\`)`);
  if (s.kind === 'props') {
    const strongest = s.ids.slice().sort((a, b) => Chem.compare(a, b).winner === a ? -1 : 1);
    p(`   - Name the IMFs first: ${s.ids.map((id) => sub(id).name + ' ' + Chem.forcesText(id) + (s.count ? ' (' + sub(id).pairs + ' hydrogen bonds)' : '')).join('; ')}.`);
    p(`   - Strongest IMFs first: ${strongest.map((id) => sub(id).name).join(' > ')}.`);
    s.props.forEach(([prop, most]) => p(`   - Which ${Chem.propAsk(prop, most, s.ids.length)}? **${sub(Chem.propBest(prop, s.ids, most)).name}**`));
  } else if (s.assign || ['phases', 'count', 'rank'].indexOf(s.kind) >= 0) {
    p(`   - Name the IMFs first: ${s.ids.map((id) => sub(id).text + ' ' + Chem.forcesText(id)).join('; ')}.`);
  }
});
p();
Object.keys(QUIZZES).forEach((k) => {
  const Q = QUIZZES[k];
  p(`## ${Q.title}`);
  p();
  p(`${Q.draw} questions per attempt from a pool of ${Q.pool.length}.`);
  p();
  Q.pool.forEach((q, n) => {
    p(`${n + 1}. ${Q.core.indexOf(q.id) >= 0 ? '★ ' : ''}\`${q.id}\`: ${q.q}`);
    p(`   - **Answer:** ${q.choices[0]}`);
    p(`   - Others: ${q.choices.slice(1).join('; ')}`);
    p(`   - Why: ${q.why}`);
  });
  p();
});
process.stdout.write(out.join('\n'));

/* tools/answer-key.js: writes the teacher's answer key as Markdown.
 *
 *   node tools/answer-key.js > ANSWER_KEY.md
 *
 * Every student gets their own numbers and substances, so the key lists the
 * plan of the graded set, every substance with its molar mass and ratios,
 * the feedback each slip gets, and a worked sample set.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const src = path.join(__dirname, '..', 'src');
const ctx = { console, Math, JSON, window: { addEventListener() {} }, document: { addEventListener() {} } };
vm.createContext(ctx);
const html = fs.readFileSync(path.join(src, 'index.html'), 'utf8');
[...html.matchAll(/<script src="([^"]+)"><\/script>/g)].forEach((m) => {
  vm.runInContext(fs.readFileSync(path.join(src, m[1]), 'utf8'), ctx, { filename: m[1] });
});
const { SUBSTANCES, Chem, Gen, App } = ctx;

const out = [];
const w = (s) => out.push(s == null ? '' : s);
const U = (t) => Chem.unitText(t);

function chainText(p) {
  const parts = [p.given.str + ' ' + U(p.fromTok)];
  p.path.forEach((t) => {
    const e = Chem.edge(t.e), top = Chem.top(t), bot = Chem.bottom(t);
    const v = (s) => (s.blank ? (e.type === 'mm' ? Chem.mmText(e.s) : String(s.v)) : Chem.valueText(s.v));
    parts.push('(' + v(top) + ' ' + U(top.t) + ' / ' + v(bot) + ' ' + U(bot.t) + ')');
  });
  return parts.join(' × ');
}

w('# Mole Conversions: answer key');
w();
w('Generated by `node tools/answer-key.js` from the model in `src/js/`. Do not edit by hand. SCHEMA ' + App.SCHEMA + '.');
w();
w('Every student gets their own substances and numbers (a seed saved with their progress), so this key gives the plan, the');
w('rules, every substance and a worked sample set. Answers are computed by the activity from the model and checked by');
w('`tools/validate.js` against a direct mole calculation and the formative quiz worked by hand.');
w();
w('## The class’s rules in the activity');
w();
w('- **Molar masses to the tenths place.** The on-screen periodic table shows every atomic mass rounded to tenths; the');
w('  molar mass is those added up (CCl₄ = 12.0 + 4(35.5) = 154.0). Also accepted: the full masses added and rounded at the');
w('  end (153.8), and the tenths value of a two-decimal table (Fe 55.85 gives 55.9, Cu 63.55 gives 63.6). The answer is');
w('  then checked against the molar mass the student typed.');
w('- **The roads:** ___ g = 1 mol (molar mass, a blank), 6.022 × 10²³ particles = 1 mol, 22.4 L = 1 mol (gases at STP only),');
w('  1 mol compound = ___ mol element (the ratio from the formula, a blank).');
w('- **Particles:** atoms of an element, molecules of a diatomic element or molecular compound. Ionic compounds are never');
w('  counted in particles (their elements are: atoms O in Fe₂O₃).');
w('- **Significant figures:** every equality counts as exact; the given quantity decides. A right number with the wrong');
w('  significant figures is not marked correct; the student is told the rule and tries again.');
w('- **Scoring:** a graded problem counts when it is right before Show solution (Show solution asks to confirm). Hints and');
w('  checking again are free. Score = problems right / 12, to `cmi.core.score.raw`; retakes keep the best.');
w();
w('## The graded set: 12 problems');
w();
w('Mixed order, never starting with a three-step problem. The direction of each is drawn at random (the likelier one first).');
w();
w('| Steps | Template | Routes |');
w('| --- | --- | --- |');
Gen.SET_PLAN.forEach((t) => {
  const T = Gen.TEMPLATES[t];
  const ways = [...new Set(T.ways.map((x) => x.join(' to ')))].join('; ').replace(/part/g, 'particles').replace(/:A/g, ' A').replace(/:B/g, ' B');
  w('| ' + T.steps + ' | `' + t + '` | ' + ways + ' |');
});
w();
w('A is the substance; B is an element counted in it. Warm-ups (ungraded, one road each): ' +
  Gen.WARM.map((x) => '`' + x + '`').join(', ') + '.');
w();
w('## Substances');
w();
w('| Formula | Kind | Particles | Gas at STP | Molar mass (g/mol) | Also accepted | Ratios (1 mol = ...) |');
w('| --- | --- | --- | --- | --- | --- | --- |');
SUBSTANCES.forEach((s) => {
  const sp = Chem.sp(s.f);
  const acc = Chem.mmAccepted(s.f).filter((a) => a !== Chem.mm10(s.f)).map((a) => (a / 10).toFixed(1)).join(', ');
  const ratios = sp.compound ? sp.order.map((b) => sp.counts[b] + ' mol ' + b).join(', ') : '';
  w('| ' + sp.disp + ' | ' + s.kind + ' | ' + (sp.part || 'not used') + ' | ' + (s.gas ? 'yes' : '') + ' | ' +
    Chem.mmWork(s.f) + ' | ' + acc + ' | ' + ratios + ' |');
});
w();
w('## Feedback on a wrong molar mass (example: Mg(NO₃)₂, 148.3)');
w();
w('| Typed | What it gets |');
w('| --- | --- |');
w('| 148.31 or 148 | ' + Chem.judgeMM('Mg(NO3)2', '148.31').msg + ' |');
Chem.mmSlips('Mg(NO3)2').forEach((sl) => w('| ' + (sl.v10 / 10).toFixed(1) + ' | ' + sl.msg + ' |'));
w();
w('Ratio blank, Mg(NO₃)₂ to O (6): 3 gets "' + Chem.judgeRatio('Mg(NO3)2', 'O', '3').msg + '"; 2 gets "' +
  Chem.judgeRatio('Mg(NO3)2', 'O', '2').msg + '"; 9 gets "' + Chem.judgeRatio('Mg(NO3)2', 'O', '9').msg + '"');
w();
w('## The formative quiz, worked the activity’s way');
w();
[['L|He', 'mol|He', 21.55, '21.55', 4], ['g|Mg(NO3)2', 'mol|Mg(NO3)2', 53.0, '53.0', 3],
 ['part|PCl3', 'g|PCl3', 8.15e25, '8.15 × 10²⁵', 3], ['g|SBr2', 'part|Br', 9.340, '9.340', 4]].forEach(([f, t, v, str, sig], i) => {
  const A = Chem.untok(f).key, B = Chem.untok(t).key;
  const ids = [...new Set(Chem.edgesOf(A).concat(Chem.edgesOf(B), Chem.ratiosOf(A)))];
  const path = Chem.route(f, t, ids);
  const p = { given: { str: str }, fromTok: f, path: path };
  w((i + 1) + '. ' + chainText(p) + ' = **' + Chem.fmtSig(Chem.chainValue(v, path), sig) + ' ' + U(t) + '** (' + path.length + ' step' + (path.length > 1 ? 's' : '') + ')');
});
w();
w('## A sample graded set (seed 1)');
w();
Gen.set(1).forEach((p, i) => {
  w((i + 1) + '. Convert ' + p.fromText + ' to ' + p.toText + ' (' + p.steps + '-step, id `' + p.id + '`)  ');
  w('   ' + chainText(p) + ' = **' + p.ansStr + ' ' + p.toText + '**');
});
w();
w('## Sample warm-ups (seed 1)');
w();
Gen.WARM.forEach((x) => {
  const p = Gen.warm(1, x);
  w('- `' + x + '`: Convert ' + p.fromText + ' to ' + p.toText + ': ' + chainText(p) + ' = **' + p.ansStr + ' ' + p.toText + '**');
});
w();
w('## Steps');
w();
w('| # | id | Title |');
w('| --- | --- | --- |');
App.STEPS.forEach((s, i) => w('| ' + (i + 1) + ' | `' + s.id + '` | ' + s.title + ' |'));
w();
w('`src/index.html?step=<id or number>` opens a step without saving; add `&seed=<n>` for a given set and `&problem=<n>` for one');
w('of its problems.');

process.stdout.write(out.join('\n') + '\n');

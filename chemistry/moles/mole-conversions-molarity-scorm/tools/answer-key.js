/* tools/answer-key.js: writes the teacher's answer key as Markdown.
 *
 *   node tools/answer-key.js > ANSWER_KEY.md
 *
 * Every student gets their own numbers and substances, so the key lists the
 * plan of the graded set, every substance with its name, molar mass and
 * ratios, the feedback each slip gets, and a worked sample set. Worked
 * solutions are LaTeX display blocks ($$ ... $$), which GitHub typesets.
 * The same file serves both mole conversion packages (config.js decides).
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const src = path.join(__dirname, '..', 'src');
const ctx = { console, Math, JSON, parseFloat, window: { addEventListener() {} }, document: { addEventListener() {} } };
vm.createContext(ctx);
const html = fs.readFileSync(path.join(src, 'index.html'), 'utf8');
[...html.matchAll(/<script src="([^"]+)"><\/script>/g)].forEach((m) => {
  vm.runInContext(fs.readFileSync(path.join(src, m[1]), 'utf8'), ctx, { filename: m[1] });
});
const { SUBSTANCES, Chem, Gen, App, CONFIG } = ctx;
const MOL = CONFIG.molarity;
const TITLE = (/<title>([^<]+)<\/title>/.exec(html) || [])[1];

const out = [];
const w = (s) => out.push(s == null ? '' : s);
const X = '×';

/* The worked chain as a LaTeX display block. Units are left uncancelled here
   (not every Markdown viewer has \cancel); the activity strikes them through. */
function chainTex(given, fromTok, toTok, path, sig) {
  const ans = Chem.fmtSig(Chem.chainValue(Chem.parseNum(given), path), sig);
  return '$$' + Chem.texChain(given, fromTok, path, {}, { answer: ans, toTok: toTok, cancel: false }) + '$$';
}

w('# ' + TITLE + ': answer key');
w();
w('Generated by `node tools/answer-key.js` from the model in `src/js/`. Do not edit by hand. SCHEMA ' + App.SCHEMA + '.');
w();
w('Every student gets their own substances and numbers (a seed saved with their progress), so this key gives the plan, the');
w('rules, every substance and a worked sample set. Answers are computed by the activity from the model and checked by');
w('`tools/validate.js` against a direct mole calculation and the formative quiz worked by hand.');
w();
w('## The class’s rules in the activity');
w();
w('- **Molar masses to the tenths place.** The on-screen periodic table shows every atomic mass rounded to tenths; the');
w('  molar mass is those added up (CCl₄ = 12.0 + 4(35.5) = 154.0). Also accepted: the full masses added and rounded at the');
w('  end (153.8), and the tenths value of a two-decimal table (Fe 55.85 gives 55.9, Cu 63.55 gives 63.6). The answer is');
w('  then checked against the molar mass the student typed.');
w('- **The roads of the mole map:** ___ g = 1 mol (the molar mass, a blank); 6.02 ' + X + ' 10²³ particles = 1 mol (Avogadro’s');
w('  number as the class rounds it); 22.4 L of gas = 1 mol (gases at STP only); 1 mol compound = ___ mol element (the ratio');
w('  from the formula, a blank)' + (MOL ? '; and 1 L solution = M mol, the molarity from the prompt, printed on its equality' : '') + '.');
if (MOL) {
  w('- **Molarity:** given in the prompt in mol/L, with the same significant figures as the volume (both are measurements). Two');
  w('  of the four molarity problems give the volume in mL, so 1000 mL = 1 L is one more step. Only substances that dissolve');
  w('  are used, at no more than half their solubility. L of solution and L of gas are different units.');
}
w('- **Particles:** atoms of an element, molecules of a diatomic element or molecular compound. Ionic compounds are never');
w('  counted in particles (their elements are: atoms O in Fe₂O₃).');
w('- **Names:** every prompt names the substance and gives its formula ("9.340 g of sulfur dibromide, SBr₂"). The chain and');
w('  the equalities use formulas.');
w('- **Significant figures:** every equality counts as exact' + (MOL ? ' except the molarity' : '') + '; the given quantity decides. A right');
w('  number with the wrong significant figures is not marked correct; the student is told the rule and tries again.');
w('- **Tolerance:** answers and molar masses within ' + Chem.TOL_TEXT + ' of the class\u2019s count, for students using other periodic tables (below).');
w('- **Scoring:** a graded problem counts when it is right before Show solution (Show solution asks to confirm). Hints and');
w('  checking again are free. Score = problems right / ' + App.GRADED + ', to `cmi.core.score.raw`; retakes keep the best.');
w('- **Worked solutions** are typeset from LaTeX: each factor a fraction, cancelled units struck through.');
w();
w('## The graded set: ' + App.GRADED + ' problems');
w();
w('Mixed order, never starting with a problem of more than one step. The direction of each is drawn at random (the likelier');
w('one first).');
w();
w('| Steps | Template | Routes |');
w('| --- | --- | --- |');
const NODE = { part: 'particles', L: 'L of gas', Lsol: 'L of solution', mLsol: 'mL of solution' };
Gen.SET_PLAN.forEach((t) => {
  const T = Gen.TEMPLATES[t];
  const ways = [...new Set(T.ways.map((x) => x.map((y) => { const [n, r] = y.split(':'); return (NODE[n] || n) + ' ' + r; }).join(' to ')))].join('; ');
  w('| ' + T.steps + ' | `' + t + '` | ' + ways + ' |');
});
w();
w('A is the substance; B is an element counted in it. Warm-ups (ungraded, one road each): ' +
  Gen.WARM.map((x) => '`' + x + '`').join(', ') + '.');
w();
w('## Substances');
w();
w('| Formula | Name | Kind | Particles | Gas at STP | ' + (MOL ? 'Solution up to | ' : '') + 'Molar mass (g/mol) | Also accepted | Ratios (1 mol = ...) |');
w('| --- | --- | --- | --- | --- | ' + (MOL ? '--- | ' : '') + '--- | --- | --- |');
SUBSTANCES.forEach((s) => {
  const sp = Chem.sp(s.f);
  const acc = Chem.mmAccepted(s.f).filter((a) => a !== Chem.mm10(s.f)).map((a) => (a / 10).toFixed(1)).join(', ');
  const ratios = sp.compound ? sp.order.map((b) => sp.counts[b] + ' mol ' + b).join(', ') : '';
  w('| ' + sp.disp + ' | ' + sp.name + ' | ' + s.kind + ' | ' + (sp.part || 'not used') + ' | ' + (s.gas ? 'yes' : '') + ' | ' +
    (MOL ? (sp.aq ? sp.maxM.toFixed(1) + ' mol/L' : '') + ' | ' : '') + Chem.mmWork(s.f) + ' | ' + acc + ' | ' + ratios + ' |');
});
w();
w('## Feedback on a wrong molar mass (example: Mg(NO₃)₂, 148.3)');
w();
w('| Typed | What it gets |');
w('| --- | --- |');
w('| 148.31 or 148 | ' + Chem.judgeMM('Mg(NO3)2', '148.31').msg + ' |');
Chem.mmSlips('Mg(NO3)2').forEach((sl) => w('| ' + (sl.v10 / 10).toFixed(1) + ' | ' + sl.msg + ' |'));
w();
w('Ratio blank, Mg(NO₃)₂ to O (6): 3 gets "' + Chem.judgeRatio('Mg(NO3)2', 'O', '3').msg + '"; 2 gets "' +
  Chem.judgeRatio('Mg(NO3)2', 'O', '2').msg + '"; 9 gets "' + Chem.judgeRatio('Mg(NO3)2', 'O', '9').msg + '"');
w();
w('## Other periodic tables: the ' + Chem.TOL_TEXT + ' tolerance');
w();
w('A molar mass written to tenths, or an answer with the right significant figures, counts when it is within ' + Chem.TOL_TEXT + ' of the');
w('class\u2019s value (an answer may also be within ' + Chem.TOL_TEXT + ' of the value from the molar masses the student typed). A rounded answer');
w('stands for everything that rounds to it, so a last digit that tips the other way still counts. Slips (a skipped subscript,');
w('a miscounted H) are still named, even when they land within ' + Chem.TOL_TEXT + '. Every problem of 100 sets and their warm-ups was worked');
w('with each table below: their own molar mass typed in the blank (to tenths) or the class\u2019s, their own masses in the');
w('calculator, the answer rounded to the right significant figures.');
w();
w('| Periodic table the student uses | Molar masses refused | Answers refused (own molar mass) | Answers refused (class molar mass) |');
w('| --- | --- | --- | --- |');
require('./tables.js')(ctx).run(100).forEach((r) => {
  w('| ' + r.name + ' | ' + r.blanks + ' of ' + r.nBlanks + ' | ' + r.own + ' of ' + r.n + ' | ' + r.cls + ' of ' + r.n + ' |');
});
w();
w('At 1% the two-decimal table (H 1.01 in grams of hydrogen) and the whole-number tables (Mg 24, Cl 35) were refused now and then;');
w('the teacher chose 1.5%. `Chem.TOL` in `src/js/chem.js` is the one number to change, and `tools/validate.js` replays these tables.');
w();
w('## The formative quiz, worked the activity’s way');
w();
[['L|He', 'mol|He', '21.55', 4], ['g|Mg(NO3)2', 'mol|Mg(NO3)2', '53.0', 3],
 ['part|PCl3', 'g|PCl3', '8.15 ' + X + ' 10²⁵', 3], ['g|SBr2', 'part|Br', '9.340', 4]].forEach(([f, t, str, sig], i) => {
  const A = Chem.untok(f).key, B = Chem.untok(t).key;
  const ids = [...new Set(Chem.edgesOf(A).concat(Chem.edgesOf(B), Chem.ratiosOf(A)))];
  const path = Chem.route(f, t, ids);
  w((i + 1) + '. ' + str + ' ' + Chem.unitText(f) + ' to ' + Chem.unitText(t) + ' (' + path.length + ' step' + (path.length > 1 ? 's' : '') + ')');
  w();
  w(chainTex(str, f, t, path, sig));
  w();
});
w('## A sample graded set (seed 1)');
w();
Gen.set(1).forEach((p, i) => {
  w((i + 1) + '. ' + p.promptText + ' (' + p.steps + '-step, id `' + p.id + '`) **' + p.ansStr + ' ' + p.toText + '**');
  w();
  w(chainTex(p.given.str, p.fromTok, p.toTok, p.path, p.given.sig));
  w();
});
w('## Sample warm-ups (seed 1)');
w();
Gen.WARM.forEach((x) => {
  const p = Gen.warm(1, x);
  w('- `' + x + '`: ' + p.promptText + ' **' + p.ansStr + ' ' + p.toText + '**');
  w();
  w(chainTex(p.given.str, p.fromTok, p.toTok, p.path, p.given.sig));
  w();
});
w('## Steps');
w();
w('| # | id | Title |');
w('| --- | --- | --- |');
App.STEPS.forEach((s, i) => w('| ' + (i + 1) + ' | `' + s.id + '` | ' + s.title + ' |'));
w();
w('`src/index.html?step=<id or number>` opens a step without saving; add `&seed=<n>` for a given set and `&problem=<n>` for one');
w('of its problems.');

process.stdout.write(out.join('\n') + '\n');

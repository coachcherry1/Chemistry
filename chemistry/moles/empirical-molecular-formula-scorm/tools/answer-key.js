/* tools/answer-key.js: writes the teacher's answer key as Markdown.
 *
 *   node tools/answer-key.js > ANSWER_KEY.md
 *
 * Every student gets their own compounds and numbers (a seed saved with
 * their progress), so the key gives the steps, the rules, the plan of the
 * graded set, every compound with what it needs, the feedback each slip
 * gets, a worked sample set and the periodic-table check. Worked solutions
 * are LaTeX display blocks ($$ ... $$), which GitHub typesets. The same file
 * serves the three formula packages (config.js decides).
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const src = path.join(__dirname, '..', 'src');
const ctx = { console, Math, JSON, parseFloat, window: { addEventListener() {}, matchMedia: () => ({ matches: false }) }, document: { addEventListener() {} } };
vm.createContext(ctx);
const html = fs.readFileSync(path.join(src, 'index.html'), 'utf8');
[...html.matchAll(/<script src="([^"]+)"><\/script>/g)].forEach((m) => {
  vm.runInContext(fs.readFileSync(path.join(src, m[1]), 'utf8'), ctx, { filename: m[1] });
});
const { FORMULAS, HYDRATES, HYDROCARBONS, PREFIXES, Chem, Gen, App, Work, CONFIG } = ctx;
const tables = require('./tables.js')(ctx);
const MODE = CONFIG.mode;
const TITLE = (/<title>([^<]+)<\/title>/.exec(html) || [])[1];

const out = [];
const w = (s) => out.push(s == null ? '' : s);
/* Markdown viewers rarely know \cancel: leave the units plain here */
const plain = (l) => l.replace(/\\cancel\{((?:[^{}]|\{[^{}]*\})*)\}/g, '$1');

function solution(p) {
  Gen.solution(p).forEach((s) => {
    w('*Step ' + s.step + ': ' + s.title + '.* ' + s.notes.join(' '));
    w();
    s.lines.forEach((l) => { w('$$' + plain(l) + '$$'); w(); });
  });
}

w('# ' + TITLE + ': answer key');
w();
w('Generated by `node tools/answer-key.js` from the model in `src/js/`. Do not edit by hand. SCHEMA ' + App.SCHEMA + '.');
w();
w('Every student gets their own compounds and numbers (a seed saved with their progress), so this key gives the steps, the');
w('rules, every compound and a worked sample set. Every number is computed by the activity from the real formula and checked by');
w('`tools/validate.js`.');
w();
w('## The four steps (the teacher’s words)');
w();
w('1. **Percents to grams:** given percents, assume a 100 g sample, so 40.0% is 40.0 g. Given grams (or masses to subtract), use the grams.');
w('2. **Grams to moles:** grams ÷ molar mass, the molar mass to the tenths place. Moles to at least 3 significant figures.');
w('3. **Divide by small:** tap the smallest mole value, divide every row by it, to two decimal places.');
w('4. **Multiply if not whole:** within 0.1 of a whole number, round (× 1). Otherwise the decimal is a fraction and every row is multiplied');
w('   by the same number: .50 × 2; .33 and .67 × 3; .25 and .75 × 4; .20, .40, .60 and .80 × 5 (halves, thirds, fourths and fifths only).');
if (MODE === 'empirical') w('5. **Molecular formula** (when a molar mass is given): empirical formula mass to the tenths place, n = molar mass ÷ it, every subscript × n.');
if (MODE === 'combustion') w('5. **Molecular formula** (when a molar mass is given): empirical formula mass to the tenths place, n = molar mass ÷ it, every subscript × n.');
if (MODE === 'hydrate') w('5. **Name the hydrate:** the Greek prefix for the waters (' + PREFIXES.map((p, i) => (i + 1) + ' ' + p).join(', ') + ') + hydrate.');
w();
if (MODE === 'hydrate') {
  w('In a hydrate the two rows are the anhydrous salt and the water. The salt is almost always the smallest, so Step 4 is the call');
  w('"within 0.1 of a whole number" (4.96 is 5). Real hydrates always come out whole, so Multiply if not whole is practised in the drills.');
  w();
}
if (MODE === 'combustion') {
  w('In combustion analysis the rows are C (from the CO₂) and H (from the H₂O). Step 1 has no percents: the grams of CO₂ and H₂O are');
  w('used as they are. Step 2 is grams of CO₂ ÷ 44.0 = mol CO₂, × 1 C per CO₂ = mol C; grams of H₂O ÷ 18.0 = mol H₂O, × 2 H per H₂O = mol H.');
  w('The solution also checks g C + g H against the mass burned.');
  w();
}
w('## Grading');
w();
w('- **The first Check of every step counts** (the teacher’s choice). The score is the steps right on the first check out of all the steps');
w('  of the graded problems, sent as `cmi.core.score.raw` (0 to 100) after every step, with one `cmi.interactions` record per step');
w('  (id `P3_C6H8O6_2moles`: problem, step number and name; what was typed; what was expected; right or wrong).');
w('- **Not an answer** (the student is told and checks again, nothing is marked): an empty box; the right number rounded too far');
w('  (moles to fewer than 3 significant figures, a quotient to fewer than 2 decimal places, grams with fewer decimals than the data,');
w('  a molar mass not to the tenths place, 3.99 for a whole number).');
w('- **Hints** are free. **Show me** appears after two misses in a step and fills it in (the step is already counted wrong).');
w('- **Tolerance:** molar masses and moles within ' + Chem.TOL_TEXT + ' (students use different periodic tables, as in mole conversions);');
w('  quotients within ' + Chem.QTOL + ' or 1%. Every box is judged against the student’s own earlier boxes, so one slip is counted once.');
w('- `completed` on the results page, no `masteryscore`, retakes give new problems and the gradebook keeps the best score.');
w();
w('Graded set: ' + Gen.PLAN.length + ' problems, ' + Gen.PLAN.map((s) => s.kind + (s.mol ? ' with a molar mass' : '')).join(', ') +
  ', in a mixed order opening with a problem' + (MODE === 'combustion' ? '' : ' from percents') + ' that needs × 1 or × 2. ' +
  (MODE === 'hydrate' ? 'At least four different numbers of waters, one of 1 or 2 and one of 6 or more.' :
    'Every set has a problem that needs × 1, × 2, × 3 and × 4 or × 5, and at least two molecular formulas with n above 1.') +
  ' No compound repeats or appears in a warm-up.');
w();
w('## The steps of the activity');
w();
w('| # | Step | id |');
w('| --- | --- | --- |');
App.STEPS.forEach((s, i) => w('| ' + (i + 1) + ' | ' + s.title + ' | `' + s.id + '` |'));
w();
w('Teacher links: `src/index.html?step=<id or number>` opens a step without saving; `&seed=5&problem=3` picks a set and a problem.');
w();

w('## The compounds');
w();
if (MODE === 'hydrate') {
  w('| Salt | Name | Waters | Hydrate | % water | Molar mass of the salt |');
  w('| --- | --- | --- | --- | --- | --- |');
  HYDRATES.forEach((c) => {
    const Ms = Chem.mmStd(c.salt), Mw = Chem.mmStd('H2O');
    w('| ' + Chem.subs(c.salt) + ' | ' + c.name + ' | ' + c.n + ' | ' + Chem.hydrateDisp(c.salt, c.n) + ', ' + c.name + ' ' + PREFIXES[c.n - 1] + 'hydrate | ' +
      (100 * c.n * Mw / (Ms + c.n * Mw)).toPrecision(3) + '% | ' + Chem.mmWork(c.salt) + ' |');
  });
} else {
  const list = MODE === 'empirical' ? FORMULAS : HYDROCARBONS;
  w('| Formula | Name | Empirical formula | Multiply by | n | Molar mass |');
  w('| --- | --- | --- | --- | --- | --- |');
  list.forEach((c) => {
    const ef = Chem.empirical(c.f);
    w('| ' + Chem.subs(c.f) + ' | ' + c.name + ' | ' + Chem.subs(ef.f) + ' | × ' + Gen.multOf(c.f) + ' | ' + ef.n +
      (MODE === 'empirical' && !c.mol ? ' (not asked)' : '') + ' | ' + Chem.mmStd(c.f).toFixed(1) + ' |');
  });
}
w();

w('## The feedback each slip gets');
w();
const ex = Gen.example();
const r0 = ex.rows[0];
const slips = [
  ['A percent as a decimal (0.699 for 69.9%)', Chem.judgeGrams('0.699', 69.9, 'pct', { pct: '69.9', dp: 1 }).msg],
  ['The water’s percent as the salt (hydrate)', Chem.judgeGrams('36.1', 63.9, 'rest', { pct: '36.1', dp: 1 }).msg],
  ['O₂’s mass for O', Chem.judgeMM('O', '32.0').msg],
  ['A molar mass not to tenths (159.61)', Chem.judgeMM('CuSO4', '159.61').msg],
  ['Grams times molar mass', Chem.judgeMoles('3900', 69.9, 55.8, 55.8, 'Fe').msg],
  ['Molar mass over grams', Chem.judgeMoles('0.798', 69.9, 55.8, 55.8, 'Fe').msg],
  ['Moles to 2 significant figures', Chem.judgeMoles('1.3', 69.9, 55.8, 55.8, 'Fe').msg],
  ['1 H per H₂O', Chem.judgePer('1', 'H', 'H2O').msg],
  ['mol H₂O as mol H', Chem.judgeAtomMoles('0.0400', 0.0400, 2, 'H', 'H2O').msg],
  ['Dividing by the largest', Chem.judgeQuotient('0.665', 1, 1, { big: 1.88, small: 1.25, mol: 1.25 }).msg],
  ['A quotient to one decimal place (1.3)', Chem.judgeQuotient('1.3', 4 / 3, 4 / 3, {}).msg],
  ['× 1 when 1.50 is not whole', Chem.judgeMultiplier('1', [1, 1.5], 2).msg],
  ['× 2 for 1.33', Chem.judgeMultiplier('2', [1, 1.33], 3).msg],
  ['× 4 for 1.50 (all whole, not the smallest)', Chem.judgeMultiplier('4', [1, 1.5], 2).msg],
  ['Rounding 1.50 to 2 instead of multiplying', Chem.judgeWhole('2', 1.5, 2, 3).msg],
  ['n upside down', Chem.judgeN('0.5', 60.1, 30.0, 2).msg],
  ['Adding n to a subscript', Chem.judgeSub('3', 2, 1, 2, 'C').msg]
];
w('| Slip | Feedback |');
w('| --- | --- |');
slips.forEach((s) => w('| ' + s[0] + ' | ' + String(s[1]).replace(/\|/g, '/') + ' |'));
w();

w('## The worked example (step `four`)');
w();
w(ex.promptText);
w();
w('**Answer: ' + ex.answerText + '.**');
w();
solution(ex);

w('## A sample graded set (seed 1)');
w();
Gen.set(1).forEach((p, i) => {
  w('### ' + (i + 1) + '. ' + p.answerText + (p.mode === 'hydrate' ? '' : ' (' + p.name + ')'));
  w();
  w(p.promptText);
  if (p.lab) { w(); p.lab.forEach((d) => w('- ' + d.label + ': ' + d.value)); }
  w();
  solution(p);
});

w('## The warm-ups (seed 1)');
w();
Gen.WARM.forEach((id) => {
  const p = Gen.warm(1, id);
  w('- `' + id + '`: ' + p.promptText + ' **' + p.answerText + '**');
});
w();

w('## The drills (seed 1)');
w();
w('- **Name the fraction:** ' + Gen.fracCards(1).map((c) => c.str + ' = ' + c.w + c.uni + ', × ' + c.den + ' → ' + c.whole).join('; ') + '.');
w('- **Whole or not?** ' + Gen.wholeCards(1).map((c) => c.str + (c.round ? ' round to ' + c.n : ' multiply (' + c.uni + ', × ' + c.mult + ')')).join('; ') + '.');
w('- **Multiply them all:** ' + Gen.allRatios(1).map((r) => r.rows.map((x) => x.sym + ' ' + x.str).join(' : ') + ' × ' + r.mult + ' → ' + r.efDisp).join('; ') + '.');
w();

w('## Other periodic tables');
w();
w('Every problem of 120 sets (and their warm-ups) worked by a student with each table: their own molar masses typed to tenths, their');
w('table’s full masses in the calculator, moles to 3 significant figures, quotients to 2 decimal places. A problem counts as refused');
w('if any box is refused or a quotient reads as another fraction. `tools/validate.js` fails on any refusal.');
w();
w('| Table | Problems | Refused |');
w('| --- | --- | --- |');
tables.run(120).forEach((r) => w('| ' + r.name + ' | ' + r.n + ' | ' + r.refused + ' |'));
w();

process.stdout.write(out.join('\n'));

/* tools/answer-key.js: writes the answer key as Markdown.
 *
 *   node tools/answer-key.js > ANSWER_KEY.md
 *
 * Everything comes from the model (vsepr.js) and the item bank, so the key
 * cannot drift from what the activity marks right.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const src = path.join(__dirname, '..', 'src');
const ctx = {
  console, Math, JSON, Object, Array, String, Number, Error, isNaN, parseInt, Date, RegExp, URLSearchParams,
  window: { matchMedia: () => ({ matches: false }), addEventListener() {} },
  document: { addEventListener() {}, documentElement: {} },
  getComputedStyle: () => ({ getPropertyValue: () => '' })
};
vm.createContext(ctx);
const html = fs.readFileSync(path.join(src, 'index.html'), 'utf8');
[...html.matchAll(/<script src="([^"]+)"><\/script>/g)].forEach((m) => {
  vm.runInContext(fs.readFileSync(path.join(src, m[1]), 'utf8'), ctx, { filename: m[1] });
});
const { SPECIES, Lewis, VSEPR, QUIZZES, App } = ctx;

const out = [];
const p = (s) => out.push(s == null ? '' : s);
const sp = (id) => Lewis.species(id);
const choiceText = (c) => typeof c === 'string' ? c : sp(c.lewis).text + ' (drawing)';

p('# VSEPR: Molecular Geometry and Polarity, answer key');
p();
p('Generated by `node tools/answer-key.js` from the model and the item bank. Do not edit by hand.');
p();
p(`${App.STEPS.length} steps; ${App.GRADED} graded questions per attempt. ★ marks a core question, asked in every attempt; ` +
  'the rest of each checkpoint is drawn at random from its pool. In the LMS, choice letters are recorded as ' +
  'a = the correct answer below, b, c, d = the others in the order listed (the screen shuffles them).');
p();
p('## Molecules');
p();
p('| Species | Name | Electron domains | Lone pairs on the central atom | Molecular geometry | Bond angle | Polar? |');
p('| --- | --- | --- | --- | --- | --- | --- |');
Object.keys(SPECIES).forEach((id) => {
  const i = VSEPR.info(id), pol = VSEPR.polar(id);
  p(`| ${sp(id).text} | ${sp(id).name} | ${i.domains} | ${i.lp} | ${i.geometry} | ${i.angle} | ${pol === null ? 'ion' : pol ? 'polar' : 'nonpolar'} |`);
});
p();
p('Angles are taught as students learn them: one lone pair <109.5°, two lone pairs <<109.5°. The 3D models of ' +
  'NH₃ and H₂O are built at their measured angles (106.7° and 104.5°), which students are never asked for.');
p();
p('## Steps');
p();
App.STEPS.forEach((s, k) => {
  const title = s.kind === 'build' ? 'Build ' + sp(s.sp).text : s.title;
  p(`${k + 1}. **${title}** (\`${s.id}\`)`);
});
p();
p('## Predictions (not graded)');
p();
Object.keys(App.PREDICT).forEach((k) => {
  const pr = App.PREDICT[k];
  const ch = pr.choices || App.fieldChoices(App.STEPS.find((s) => s.id === 'field').set);
  p(`- ${pr.q} **${ch[pr.answer]}**`);
});
p();
Object.keys(QUIZZES).forEach((k) => {
  const Q = QUIZZES[k];
  p(`## ${Q.title}`);
  p();
  p(`${Q.draw} questions per attempt from a pool of ${Q.pool.length}.`);
  p();
  Q.pool.forEach((q, n) => {
    const star = Q.core.indexOf(q.id) >= 0 ? '★ ' : '';
    p(`${n + 1}. ${star}\`${q.id}\`: ${q.q}${q.fig ? ' (shows the Lewis structure of ' + sp(q.fig.lewis).text + ')' : ''}`);
    p(`   - **Answer:** ${choiceText(q.choices[0])}`);
    p(`   - Others: ${q.choices.slice(1).map(choiceText).join('; ')}`);
    p(`   - Why: ${q.why}`);
  });
  p();
});
process.stdout.write(out.join('\n'));

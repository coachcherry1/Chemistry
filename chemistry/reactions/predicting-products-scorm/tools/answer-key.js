/* tools/answer-key.js: writes the answer key from the model.
 *
 *   node tools/answer-key.js > ANSWER_KEY.md
 *
 * Every answer is worked out by Ions (the handout) and Chem.balance, exactly
 * as in the activity.
 */
const { load } = require('./load.js');
const { Chem, Ions, Gen, Steps, App } = load();
const out = [];
const p = (s) => out.push(s);
const ion = (k, cat) => { const t = cat ? Ions.CATIONS[k] : Ions.ANIONS[k]; return Chem.pretty(t[0]) + (t[1] > 1 ? t[1] : '') + (cat ? '+' : '−'); };

p('# Predicting products: answer key');
p('');
p('Generated by `node tools/answer-key.js`. Do not edit by hand.');
p('');
p('Each student gets ' + Gen.QUIZ + ' graded questions and ' + Gen.COUNT + ' graded problems: five single replacements (three metals with a salt, ' +
  'one metal with an acid, one halogen; two of the five do not react) and five double replacements (one gives no reaction). Every step of a ' +
  'problem is one graded item, 33 in all, so the score is items right the first time / 37.');
p('');
p('## The reference on screen (the class handout)');
p('');
p('**Activity series, most active first:** ' + Ions.SERIES.map((m) => (m[0] === 'H' ? '**H₂**' : m[0])).join(', ') + '. Halogens: F₂ > Cl₂ > Br₂ > I₂.');
p('');
p('**Solubility.** Always soluble: compounds of ' + Ions.TABLE.always.map((c) => ion(c, true)).join(', ') + '.');
p('');
p('| Soluble | unless with | | Insoluble | unless with |');
p('| --- | --- | --- | --- | --- |');
for (let i = 0; i < Math.max(Ions.TABLE.soluble.length, Ions.TABLE.insoluble.length); i++) {
  const a = Ions.TABLE.soluble[i], b = Ions.TABLE.insoluble[i];
  p('| ' + (a ? Ions.ANIONS[a[0]][2] + ' ' + ion(a[0]) : '') + ' | ' + (a ? a[1].map((c) => ion(c, true)).join(', ') || 'none' : '') + ' | | ' +
    (b ? Ions.ANIONS[b[0]][2] + ' ' + ion(b[0]) : '') + ' | ' + (b ? b[1].map((c) => ion(c, true)).join(', ') : '') + ' |');
}
p('');
p('Never used, as a reactant or a product, because the real compound is only slightly soluble, reacts with water or does not exist: ' +
  Ions.AVOID.filter((x) => !/^Li /.test(x)).map((x) => { const t = x.split(' '); return Chem.pretty(Ions.formula(t[0], t[1])); }).join(', ') + '.');
p('');
p('## The lesson (not graded)');
p('');
p('**Reading the activity series**');
p('');
Steps.WILLIT.forEach((w, i) => { const q = Gen.make(w[0], w[1]); p((i + 1) + '. ' + Gen.equation(q, true) + '. ' + q.why); });
p('');
p('**Reading the solubility table**');
p('');
Steps.SOL.forEach((f, i) => p((i + 1) + '. ' + Chem.pretty(f) + ', ' + Ions.name(f) + ': **(' + Ions.state(f) + ')**'));
p('');
p('**Worked problems**');
p('');
App.STEPS.filter((s) => s.kind === 'ladder').forEach((s) => { const q = Gen.make(s.l[0], s.l[1]); p('- ' + s.title + ': ' + Gen.equation(q, true) + '. ' + q.why); });
p('');
p('## Graded problems: the pools');
p('');
const P = Gen.pools();
const TITLE = { metalYes: 'A metal and a salt: reacts', metalNo: 'A metal and a salt: no reaction', acidYes: 'A metal and an acid: reacts', acidNo: 'A metal and an acid: no reaction',
  halYes: 'A halogen and a halide: reacts', halNo: 'A halogen and a halide: no reaction' };
Object.keys(TITLE).forEach((k) => {
  p('### ' + TITLE[k] + ' (' + P[k].length + ')');
  p('');
  P[k].forEach((q) => p('- ' + Gen.equation(q, true)));
  p('');
});
p('### Double replacement');
p('');
p(P.drYes.length + ' pairs of solutions give a solid and ' + P.drNo.length + ' give no reaction: every pair of soluble compounds of ' +
  Gen.DR_CATS.map((c) => ion(c, true)).join(', ') + ' with ' + Gen.DR_ANS.map((a) => ion(a)).join(', ') + ' whose products are both usable. The solids that can form:');
p('');
const solids = {};
P.drYes.forEach((q) => q.solids.forEach((f) => { solids[f] = 1; }));
p(Object.keys(solids).sort().map((f) => Chem.pretty(f)).join(', ') + '.');
p('');
p('## Graded questions');
p('');
p('1. Which of four metals will replace aluminum, zinc or iron: the one above it in the series.');
p('2. Which of four metals will not react with hydrochloric acid: copper or silver (below hydrogen).');
p('3. Which of four compounds is insoluble: by the table.');
p('4. Which of four pairs of solutions gives no reaction: the pair whose two products are both soluble.');
p('');
p('## One student, as an example (seed 1)');
p('');
Gen.quiz(1).forEach((q, i) => {
  p((i + 1) + '. ' + q.stem);
  q.choices.forEach((c, k) => p('   - ' + (k === q.right ? '**' + c + '**' : c)));
});
p('');
Gen.set(1).forEach((q, i) => p((i + 1) + '. ' + q.prompt + ' **' + Gen.equation(q, true) + '**'));
console.log(out.join('\n'));

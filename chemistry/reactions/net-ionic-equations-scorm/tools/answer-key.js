/* tools/answer-key.js: writes the answer key (markdown) from the model.
 *
 *   node tools/answer-key.js > ANSWER_KEY.md
 */
const { load } = require('./load');
const { Net, Gen, App, CONFIG } = load();

const out = [];
const w = (s) => out.push(s == null ? '' : s);
function problem(p, n) {
  w((n ? n + '. ' : '') + '**' + p.prompt + '** (' + { solid: 'a solid forms', water: 'water forms', none: 'no reaction', both: 'a solid and water' }[p.kind] + ')');
  w();
  w('   - Given: ' + p.unbalanced);
  w('   - Balanced, with states: ' + Net.molecularText(p));
  w('   - Complete ionic: ' + Net.ionicText(p));
  w('   - Spectators: ' + (p.spect.length ? Net.spectText(p) : 'none'));
  w('   - Net ionic: **' + Net.netText(p) + '**');
  w();
}

w('# Net Ionic Equations: answer key');
w();
w('Generated by `node tools/answer-key.js` from the model in `src/js/net.js` (do not edit by hand). SCHEMA ' + App.SCHEMA + ', about ' + CONFIG.minutes + ' minutes.');
w();
w('Every student gets a different set of problems and questions from a random seed; retakes get new ones. To see any');
w('student\'s set, open `src/index.html?step=set&seed=<n>&problem=<1 to 8>&done` (or `&rung=<1 to 5>`), and');
w('`?step=quiz&seed=<n>` for the questions. The seed is kept in the student\'s saved state.');
w();
w('## Scope');
w();
w('- Reactants: soluble salts (by the class solubility rules, the same data as package 3), the strong acids ' + Net.STRONG_ACIDS.join(', ') +
  ' and the strong bases ' + Net.STRONG_BASES.join(', ') + '. No weak acids or bases, no gases, no solid reactants.');
w('- Products: a solid, water (written HOH), or nothing (no reaction). Ammonium, acetate and sulfide are not used; an acid never meets a carbonate or a phosphate.');
w('- Every problem gives the unbalanced molecular equation. Five steps, each graded on the first Check: balance, states, complete ionic, spectators, net ionic.');
w('- Graded: ' + Gen.QUIZ + ' questions and ' + Gen.COUNT + ' problems (3 that make a solid, 2 that make water, one of which must be reduced to lowest terms, 2 with no reaction, and last the challenge) = ' +
  (Gen.QUIZ + Gen.COUNT * Gen.RUNGS.length) + ' items.');
const P = Gen.pools();
w('- Pools: ' + P.solid.length + ' pairs that make a solid, ' + P.water.length + ' acid and base pairs, ' + P.none.length + ' pairs with no reaction (lesson reactions excluded).');
w();
w('## The lesson (not graded)');
w();
w('**What (aq) looks like:** ' + Gen.LESSON.aq.map((f) => Net.pretty(f) + '(' + Net.state(f) + ')').join(', ') + '. The right picture shows the ions apart in the formula\'s ratio (a solid: on the bottom).');
w();
w('**Writing a substance as its ions** (the first is a worked example):');
w();
Gen.LESSON.split.forEach(([f, c]) => {
  const st = Net.state(f);
  w('- ' + (c > 1 ? c + ' ' : '') + Net.pretty(f) + '(' + st + ') → ' + (st === 'aq' ? Net.sideText(Net.split(f, c, 'aq')) : 'stays together'));
});
w();
w('**Watch it happen** (a prediction, then the beaker):');
w();
['solid', 'water', 'none'].forEach((k) => {
  const o = require('./load').load().Steps.WATCH[k];
  w('- ' + o.title + ': ' + o.choices.find((c) => c.ok).t + '. ' + o.done);
});
w();
w('**Worked on the five steps:**');
w();
['exSolid', 'exWater', 'exNone'].forEach((k) => problem(Net.make(Gen.LESSON[k][0], Gen.LESSON[k][1])));
w('## Example graded set (seed 1)');
w();
const set = Gen.set(1);
set.forEach((p, i) => problem(p, i + 1));
w('## Example questions (seed 1)');
w();
Gen.quiz(1).forEach((q, i) => {
  w((i + 1) + '. ' + q.stem);
  w('   - Answer: **' + q.choices[q.right] + '**');
  w('   - Why: ' + q.why);
  w();
});
w('## The challenge (every set ends with it)');
w();
problem(Net.make(Gen.CHALLENGE[0], Gen.CHALLENGE[1]));
console.log(out.join('\n'));

/* tools/answer-key.js: writes the answer key from the model.
 *
 *   node tools/answer-key.js > ANSWER_KEY.md
 *
 * Every coefficient is worked out by Chem.balance, exactly as in the activity.
 */
const { load } = require('./load.js');
const { Chem, Rx, Gen, Steps, App, CONFIG } = load();
const out = [];
const p = (s) => out.push(s);
const LEVEL = { 1: 'Easy', 2: 'Medium', 3: 'Hard' };
const inv = (x) => x.left + ' | ' + x.label + (x.other.length ? ' (not in ' + x.other.map(Chem.pretty).join(', ') + ')' : '') + ' | ' + x.right;

if (CONFIG.classify) {
  /* the classifying package */
  const eq = (r) => Chem.equation(r, Chem.balance(r));
  p('# Balancing and reaction types: answer key');
  p('');
  p('Generated by `node tools/answer-key.js`. Do not edit by hand.');
  p('');
  p('Each student gets ' + Gen.QUIZ + ' graded questions and ' + Gen.COUNT + ' graded reactions, each balanced and classified together (two items: ' +
    'the coefficients and the type, both judged by the first Check). Every set has all six types, easiest first, and ends with nitroglycerin. ' +
    'Score = items right the first time / ' + App.ITEMS + '.');
  p('');
  p('## The six types');
  p('');
  p('| Type | General form | What gives it away | Example in the lesson |');
  p('| --- | --- | --- | --- |');
  Chem.TYPE_ORDER.forEach((t) => p('| ' + Chem.TYPES[t].name + ' | ' + Chem.TYPES[t].form + ' | ' + Chem.TYPES[t].clue + ' | ' + eq(Rx.get(Steps.EXAMPLES[t])) + ' |'));
  p('');
  p('**Three rules for close calls**');
  p('');
  Steps.RULES3.forEach((t, i) => p((i + 1) + '. ' + t));
  p('');
  p('## The lesson (not graded)');
  p('');
  App.STEPS.filter((s) => s.kind === 'bench').forEach((s) => {
    const r = Rx.get(s.rx);
    p('- ' + s.title + ': ' + eq(r) + (s.classify ? ' (**' + Chem.TYPES[r.type].name + '**)' : ''));
  });
  p('');
  p('**Which type?**');
  p('');
  Steps.SORT.forEach((id, i) => { const r = Rx.get(id); p((i + 1) + '. ' + eq(r) + ': **' + Chem.TYPES[r.type].name + '**'); });
  p('');
  p('## Graded reactions: the pool');
  p('');
  Chem.TYPE_ORDER.forEach((t) => {
    const list = Gen.typedPool().filter((r) => r.type === t).concat(t === 'D' ? [Rx.get(Gen.CORE)] : []);
    p('### ' + Chem.TYPES[t].name + ' (' + list.length + ')');
    p('');
    p('| Unbalanced | Balanced | Coefficients | Level |');
    p('| --- | --- | --- | --- |');
    list.forEach((r) => p('| ' + Chem.equation(r) + ' | ' + eq(r) + ' | ' + Chem.balance(r).join(', ') + ' | ' + LEVEL[r.level] + (r.id === Gen.CORE ? ' (every student, last)' : '') + ' |'));
    p('');
  });
  p('## Graded questions: the pools');
  p('');
  p('1. **A general form** (S, D, SR or DR): which type has it.');
  p('2. **A rule** (one per student):');
  Gen.TYPE_RULES.forEach((r) => p('   - ' + r.stem + ' **' + r.c[0] + '.** ' + r.why));
  p('3. **Which of these is a ... reaction?** Four balanced equations of four different types from the pool above.');
  p('4. **What type does this picture show?** A particle picture of a small balanced reaction from the pool.');
  p('');
  p('## One student, as an example (seed 1)');
  p('');
  Gen.quiz(1).forEach((q, i) => {
    p((i + 1) + '. ' + q.stem + (q.fig ? ' (picture: ' + Chem.equation(q.fig.rx, q.fig.coefs) + ')' : ''));
    q.choices.forEach((c, k) => p('   - ' + (k === q.right ? '**' + c + '**' : c)));
  });
  p('');
  Gen.set(1).forEach((s, i) => p((i + 1) + '. ' + Chem.equation(s.rx, s.coefs) + ': **' + Chem.TYPES[s.type].name + '**'));
  console.log(out.join('\n'));
  process.exit(0);
}

p('# Balancing equations with particles: answer key');
p('');
p('Generated by `node tools/answer-key.js`. Do not edit by hand.');
p('');
p('Each student gets ' + Gen.QUIZ + ' graded questions and ' + Gen.COUNT + ' graded equations (' +
  Gen.PLAN.map((pl) => pl[1] + ' ' + LEVEL[pl[0]].toLowerCase()).join(', ') + '), drawn at random. Score = items right the first time / ' + App.ITEMS + '.');
p('');
p('## The lesson (not graded)');
p('');
p('**Subscripts and coefficients**');
p('');
Steps.COUNT.forEach((c) => {
  const per = Chem.parse(c[1]);
  p('- ' + c[0] + ' ' + Chem.pretty(c[1]) + ': ' + Object.keys(per).map((el) => c[0] * per[el] + ' ' + el).join(', '));
});
p('');
p('**What may you change?** Write 2 H₂O (a coefficient). Changing a subscript changes the substance.');
p('');
p('**Is it conserved?**');
p('');
Steps.CARDS.forEach((c, i) => {
  const r = Rx.get(c.rx), t = Chem.tally(r, c.c), off = t.filter((x) => !x.ok);
  p((i + 1) + '. ' + Chem.equation(r, c.c) + ': ' + (off.length ? 'not conserved (' + off.map((x) => x.el + ' ' + x.left + ' before, ' + x.right + ' after').join('; ') + ')' : 'conserved'));
});
p('');
p('**Balancing and polyatomic ions** (the inventory is shown for the equation as written, reactants | row | products)');
p('');
App.STEPS.filter((s) => s.kind === 'bench').forEach((s) => {
  const r = Rx.get(s.rx), ones = Chem.species(r).map(() => 1);
  p('- ' + s.title + ': ' + Chem.equation(r, Chem.balance(r)));
  p('  - Inventory' + (s.typed ? ' (typed by the student)' : '') + ': ' + Chem.inventory(r, ones).map(inv).join('; '));
  if (s.ask) p('  - Prediction: ' + s.ask.q + ' **' + s.ask.c.filter((c) => c.ok)[0].t + '**');
});
p('');
p('## Graded equations: the pool');
p('');
[1, 2, 3].forEach((lv) => {
  p('### ' + LEVEL[lv] + ' (' + Gen.PLAN.filter((pl) => pl[0] === lv)[0][1] + ' of ' + Gen.pool(lv).length + ' per student)');
  p('');
  p('| Unbalanced | Balanced | Coefficients | Inventory rows |');
  p('| --- | --- | --- | --- |');
  Gen.pool(lv).forEach((r) => {
    const c = Chem.balance(r);
    p('| ' + Chem.equation(r) + ' | ' + Chem.equation(r, c) + ' | ' + c.join(', ') + ' | ' + Chem.rows(r).rows.map((x) => x.label + (x.other.length ? '*' : '')).join(', ') + ' |');
  });
  p('');
  p('\\* the atoms of that element that are not inside a kept ion.');
  p('');
});
p('## Graded questions: the pools');
p('');
p('**Counting atoms** (one plain, one with brackets per student)');
p('');
Gen.COUNT_PLAIN.concat(Gen.COUNT_BRACKET).forEach((it) => {
  p('- ' + it[2] + ' atoms in ' + it[0] + ' ' + Chem.pretty(it[1]) + ': **' + it[0] * Chem.parse(it[1])[it[2]] + '**');
});
p('');
p('**A rule** (one per student)');
p('');
Gen.RULES.forEach((r) => { p('- ' + r.stem + ' **' + r.c[0] + '.** ' + r.why); });
p('');
p('**Is the picture conserved?** (two per student: one conserved, one with exactly one element off). The pictures are drawn from: ' +
  Gen.small().map((r) => Chem.equation(r, Chem.balance(r))).join('; ') + '. A conserved picture may show every coefficient doubled: it is still conserved.');
p('');
p('**Starting an inventory** (one per student): how many of a polyatomic ion are on each side of the equation as written.');
p('');
Gen.ionList().forEach((it) => p('- ' + Chem.equation(it.rx) + ': ' + it.row.label + ' **' + it.row.left + ' in the reactants, ' + it.row.right + ' in the products**'));
p('');
p('## Reactions kept for the classifying package (too many particles for this one)');
p('');
Rx.REACTIONS.filter((r) => r.big).forEach((r) => p('- ' + Chem.equation(r, Chem.balance(r))));
p('');
p('## One student, as an example (seed 1)');
p('');
Gen.quiz(1).forEach((q, i) => {
  p((i + 1) + '. ' + q.stem + (q.fig ? ' (picture: ' + Chem.equation(q.fig.rx, q.fig.coefs) + ')' : ''));
  q.choices.forEach((c, k) => p('   - ' + (k === q.right ? '**' + c + '**' : c)));
});
p('');
Gen.set(1).forEach((s, i) => p((i + 1) + '. ' + Chem.equation(s.rx, s.coefs)));
console.log(out.join('\n'));

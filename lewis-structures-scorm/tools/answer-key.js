const out = [];
const P = (s = '') => out.push(s);
const BOND = { 1: 'single', 2: 'double', 3: 'triple' };

function sumText(v) {
  return v.rows.map((r) => (r.n > 1 ? `${r.n} × ${r.each}` : String(r.each))).join(' + ') +
    (v.adjust ? (v.adjust > 0 ? ' + ' : ' − ') + Math.abs(v.adjust) : '') + ` = ${v.total}`;
}

function rule5(sp, r) {
  if (!r.moves.length) {
    if (ELEMENTS[sp.center].stable) return `${sp.center} has ${r.centerAfter4} — **stable with ${r.centerAfter4}** (exception), nothing to do`;
    if (r.centerAfter4 > 8) return `${sp.center} has ${r.centerAfter4} — **expanded octet** from Rule ${Lewis.bondsOf(r.s2, 'C').length > 4 ? 2 : 4}, nothing to do`;
    return `${sp.center} has 8 — nothing to do`;
  }
  const n = r.moves.length;
  return `${sp.center} has ${r.centerAfter4}; ${n} lone pair${n > 1 ? 's' : ''} → ` +
    Lewis.DIRS.filter((d) => r.s5.bo[d] > 1).map((d) => `${BOND[r.s5.bo[d]]} bond to ${r.s5.at[d]}`).join(', ');
}

function alsoAccepted(sp) {
  const canon = JSON.stringify(Lewis.canonical(sp));
  const alts = Lewis.rule5Outcomes(sp).filter((s) => JSON.stringify(s) !== canon).map((s) => {
    const parts = Lewis.DIRS.filter((d) => s.at[d] && s.at[d] !== 'H').map((d) =>
      `${BOND[s.bo[d]]} bond to ${Lewis.carriesH(s, d) ? 'an O–H oxygen' : s.at[d]}`);
    return parts.sort().join(', ');
  });
  return [...new Set(alts)];
}

function speciesRow(sp) {
  const r = Lewis.solve(sp);
  return `| ${sp.text} | ${sp.name} | ${sumText(r.valence)} | ${r.bonds} bonds: −${r.used2} → ${r.left2} | ` +
    `−${2 * r.outerLP} → ${r.left3} | ${Lewis.pairs(r.centerLP)} on ${sp.center} | ${rule5(sp, r)} |`;
}


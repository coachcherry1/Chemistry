function choiceText(c) {
  if (typeof c === 'string') return c;
  if (c.hybrid) return `[drawing of ${Lewis.species(c.hybrid).text}] ${VARIANT[c.variant || 'hybrid']}`;
  const sp = Lewis.species(c.lewis);
  return `[drawing] ${Lewis.describe(Lewis.variant(sp, c.mod))}`;
}


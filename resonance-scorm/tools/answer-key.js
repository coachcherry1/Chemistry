const BOND = { 1: 'single', 2: 'double', 3: 'triple' };
const WHERE = { N: 'top', S: 'bottom', E: 'right', W: 'left', NE: 'upper right', NW: 'upper left', SE: 'lower right',
  SW: 'lower left' };

function sumText(v) {
  return v.rows.map((r) => (r.n > 1 ? `${r.n} × ${r.each}` : String(r.each))).join(' + ') +
    (v.adjust ? (v.adjust > 0 ? ' + ' : ' − ') + Math.abs(v.adjust) : '') + ` = ${v.total}`;
}

function rule5(sp, r) {
  const n = r.moves.length;
  return `${sp.center} has ${r.centerAfter4}; ${n} lone pair${n > 1 ? 's' : ''} from an O → ${BOND[1 + n]} bond — ` +
    `**any** of the ${Hybrid.compute(sp).cloud.length} O atoms will do`;
}

function speciesRow(sp) {
  const r = Lewis.solve(sp);
  return `| ${sp.text} | ${sp.name} | ${sumText(r.valence)} | ${r.bonds} bonds: −${r.used2} → ${r.left2} | ` +
    `−${2 * r.outerLP} → ${r.left3} | ${Lewis.pairs(r.centerLP)} on ${sp.center} | ${rule5(sp, r)} |`;
}

/* "A: double bond to the top O" */
function structureText(s, i) {
  const d = Lewis.DIRS.filter((k) => s.at[k] && s.bo[k] > 1);
  return `${String.fromCharCode(65 + i)}: ${d.map((k) => `${BOND[s.bo[k]]} bond to the ${WHERE[k]} ${s.at[k]}`).join(', ')}`;
}

function hybridBlock(sp) {
  const h = Hybrid.compute(sp);
  const b = BONDS[sp.id];
  const neg = Object.keys(h.marks).filter((k) => h.marks[k] === 'δ−').map((k) => h.base.at[k]);
  P(`**${sp.text}** — ${h.n} resonance structures (${h.structures.map(structureText).join(' ↔ ')})`);
  P();
  P(`- Hybrid: ${h.cloud.length} identical ${Hybrid.pairName(sp)} bonds, bond order **${h.order}** ` +
    `= (2${' + 1'.repeat(h.n - 1)}) ÷ ${h.n}`);
  P(`- δ−: ${neg.length === h.cloud.length ? 'every' : neg.length} outer ${[...new Set(neg)].join('/')}` +
    (h.marks.C === 'δ+' ? `; δ+: the central ${sp.center}` : '') +
    (sp.charge ? ` (the ${Math.abs(sp.charge)}${sp.charge < 0 ? '−' : '+'} charge is shared out)` : ''));
  const other = Lewis.DIRS.filter((k) => h.base.at[k] && h.cloud.indexOf(k) < 0);
  if (other.length) P(`- Not shared: ${other.map((k) => `${sp.center}–${h.base.at[k]}`).join(', ')} stays a single bond`);
  if (b) P(`- Evidence: ${b.pair} single ${b.single} pm, ${b.pair.replace('–', '=')} double ${b.double} pm, measured in ` +
    `${sp.text} **${b.actual} pm** (${h.cloud.length === 2 ? "both" : "all " + h.cloud.length} the same)`);
  P();
}


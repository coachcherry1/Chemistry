/* tools/answer-key.js: prints the teacher's answer key as Markdown, every
 * answer computed by the model the activity itself uses.
 *
 *   node tools/answer-key.js > ANSWER_KEY.md
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const src = path.join(__dirname, '..', 'src');
const noop = () => {};
const fakeEl = () => ({ setAttribute: noop, appendChild: noop, addEventListener: noop, classList: { add: noop, toggle: noop }, style: {} });
const ctx = {
  console, Math, JSON, Object, Array, String, Number, Error, setTimeout, URLSearchParams,
  window: { matchMedia: () => ({ matches: false }), addEventListener: noop },
  document: { addEventListener: noop, createElement: fakeEl, createElementNS: fakeEl, createTextNode: fakeEl, getElementById: fakeEl },
  localStorage: { getItem: () => null, setItem: noop, removeItem: noop }, location: { search: '' }, navigator: {},
  requestAnimationFrame: noop, cancelAnimationFrame: noop
};
vm.createContext(ctx);
['chem', 'scenes', 'judge', 'render', 'arrows', 'energy', 'picker', 'quiz', 'scorm', 'app', 'steps1', 'steps2'].forEach((f) =>
  vm.runInContext(fs.readFileSync(path.join(src, 'js', f + '.js'), 'utf8').replace(/^if \(typeof module.*$/m, ''), ctx));
const { Chem, SCENES, Judge, QUIZZES, App } = vm.runInContext('({ Chem, SCENES, Judge, QUIZZES, App })', ctx);
const S = SCENES.S;
const PN = Chem.PATTERN;

const out = [];
const w = (t) => out.push(t == null ? '' : t);
const cap = (t) => t.charAt(0).toUpperCase() + t.slice(1);
const pats = (sc) => sc.patterns.map((p) => PN[p]).join(' + ') + (sc.patterns.length > 1 ? ' (concerted)' : '');
function arrows(sc) {
  return sc.picks.map((m, k) => `${k + 1}. ${cap(Judge.describe(sc, sc.before, m))}.`).join('<br>');
}
function ledger(sc) {
  const L = Chem.ledger(sc.before, sc.after);
  const nm = (st, b) => {
    const e = [Chem.atom(st, b.a).el, Chem.atom(st, b.b).el];
    if (e[1] === 'C' || (e[1] === 'H' && e[0] !== 'C')) e.reverse();
    return e.join(b.pi ? '=' : '–') + (b.pi ? ' pi' : '');
  };
  return 'broken (energy in): ' + (L.broken.map((b) => nm(sc.before, b)).join(', ') || 'none') + '; formed (energy out): ' + (L.formed.map((b) => nm(sc.after, b)).join(', ') || 'none');
}

w('# Reactivity and Arrow Pushing: answer key');
w();
w('Generated by `node tools/answer-key.js` from the model the activity uses (chem.js): every product is what the arrows make, and every pattern is');
w('read from the bonds that change. Klein, *Organic Chemistry*, chapter 6. Nothing is graded except the four checkpoints.');
w();
w(`${App.STEPS.length} steps; ${App.GRADED} graded questions per attempt from a pool of ${Object.values(QUIZZES).reduce((t, Q) => t + Q.pool.length, 0)}.`);
w();
w('## Steps');
w();
w('| # | Step | Part |');
w('| --- | --- | --- |');
App.STEPS.forEach((s, i) => w(`| ${i + 1} | ${s.title} | ${s.part} |`));
w();

w('## Part 1: energy and bonds');
w();
w('**Predictions.** ' + Object.keys(App.PREDICT).filter((k) => ['breakE', 'spread', 'peak'].indexOf(k) >= 0).map((k) => `${App.PREDICT[k].q} *${App.PREDICT[k].choices[App.PREDICT[k].answer]}*`).join(' '));
w();
w('**Homolytic or heterolytic.** Two fish-hooks, one electron to each atom: two radicals. One curved arrow, both electrons to Cl: two ions (H⁺ and Cl⁻). Ionic mechanisms use heterolytic steps.');
w();
w('**Bonds broken, bonds formed** (bar heights from Klein Table 6.1, kJ/mol; students never add them):');
w();
for (const id of ['bdeA', 'bdeB']) {
  const sc = S[id], L = Chem.ledger(sc.before, sc.after);
  const v = (b) => sc.bde[Chem.keys.pair(b.a, b.b)];
  const nm = (st, b) => { const e = [Chem.atom(st, b.a).el, Chem.atom(st, b.b).el]; if (e[1] === 'C' || (e[1] === 'H' && e[0] !== 'C')) e.reverse(); return e.join('–'); };
  w(`- ${sc.title}: broken ${L.broken.map((b) => nm(sc.before, b) + ' ' + v(b)).join(', ')}; formed ${L.formed.map((b) => nm(sc.after, b) + ' ' + v(b)).join(', ')}. ` +
    `${sc.kleinH < 0 ? 'Exothermic' : 'Endothermic'} (Klein: ΔH° = ${sc.kleinH > 0 ? '+' : '−'}${Math.abs(sc.kleinH)} kJ/mol).`);
}
w();
w('**Entropy.** ΔS > 0: a C–Br bond breaking into two ions; cyclohexene splitting into butadiene and ethylene. ΔS < 0: water joining a carbocation; butadiene and ethylene making cyclohexene; a chain closing into a ring.');
w();
w('**ΔG = ΔH − TΔS.** ΔH −, ΔS +: favorable at every temperature. ΔH +, ΔS −: at no temperature. ΔH −, ΔS −: only at low temperature. ΔH +, ΔS +: only at high temperature.');
w();
w('**Energy diagrams.** Klein Figure 6.23 (two steps): two transition states, one intermediate (the carbocation). Figure 6.22 (one step): one transition state, no intermediate.');
w();

w('## Part 2: nucleophiles and electrophiles');
w();
w('CH₃Cl: the carbon is δ+ (electrophilic). CH₃Li: the carbon is δ− (nucleophilic).');
w();
w('| Card | Answer |');
w('| --- | --- |');
App.SORT_IDS.forEach((id) => w(`| ${S[id].label || S[id].title} | ${App.roleOf(id) === 'nuc' ? 'Nucleophile' : 'Electrophile'} |`));
w();
for (const id of ['sb62', 'p69', 'bromobutene']) {
  const c = Chem.centres(S[id].before);
  const name = (x) => Judge.name({}, S[id].before, x);
  w(`- ${S[id].title}: nucleophilic ${c.nuc.map((x) => name(x) + ' of the OH').concat(c.pi.map(() => 'the C=C pi bond')).join(', ') || 'none'}; electrophilic ${c.elec.map((x) => 'the C bonded to ' + Chem.neighbours(S[id].before, x).map((n) => Chem.atom(S[id].before, n.id).el).filter((e) => e !== 'C').join(' and ')).join(', ')}.`);
}
w();

w('## Parts 3 and 4: every mechanism step');
w();
w('| Scene | Arrows | Pattern | Bonds |');
w('| --- | --- | --- | --- |');
const listed = new Set();
const order = [];
App.STEPS.forEach((s) => {
  (s.scenes || []).forEach((x) => order.push(x));
  if (s.chain) S[s.chain].forEach((x) => order.push(x.id));
});
['demoPT', 'sn2'].concat(S.ester.map((x) => x.id), S.f623.map((x) => x.id), ['f622']).forEach((x) => order.push(x));
Object.values(QUIZZES).forEach((Q) => Q.pool.forEach((q) => { if (q.draw) order.push(q.draw); }));
order.forEach((id) => {
  if (listed.has(id)) return;
  listed.add(id);
  const sc = S[id];
  const label = sc.chain ? { f623: 'Klein Figure 6.23', f631: 'Klein Figure 6.31', ester: 'Klein SkillBuilder 6.4' }[sc.chain] + ', step ' + sc.n : sc.title || id;
  w(`| ${label} | ${arrows(sc)} | ${pats(sc)} | ${ledger(sc)} |`);
});
w();
w('**Klein’s rules (step 12).** ' + SCENES.RULES.map((r) => {
  const res = Chem.apply(S[r.scene].before, r.arrows);
  return `${r.label}: ${res.err ? 'breaks a rule (' + Judge.ruleText(S[r.scene], S[r.scene].before, res) + ')' : 'follows the rules'}`;
}).join(' '));
w();
w('**Carbocation stability.** Methyl < 1° < 2° < 3° (hyperconjugation).');
w();
w('**Will it rearrange?** ' + App.STEPS.find((s) => s.id === 'rearrange').mols.map((id) => `${S[id].title}: ${['a hydride shift', 'a methyl shift', 'no'][App.shiftAnswer(id)]}`).join('; ') + '.');
w();
w('**Say it in words.** ' + Object.keys(App.SAY).map((k) => {
  const sp = App.SAY[k], words = sp[sp.length - 1];
  return sp.slice(0, -1).map((x) => typeof x === 'number' ? '**' + words[x] + '**' : x).join('');
}).join(' '));
w();

w('## Checkpoints');
w();
for (const k of Object.keys(QUIZZES)) {
  const Q = QUIZZES[k];
  w(`### ${Q.title}`);
  w();
  w(`${Q.draw} per attempt. Always: ${Q.core.join(', ')}.` + (Q.pick ? ' One of each: ' + Q.pick.map((g) => g.join(' / ')).join('; ') + '.' : ''));
  w();
  Q.pool.forEach((q) => {
    if (q.draw) { w(`- **${q.id}** (graded drawing, first Check counts) ${q.q} *${arrows(S[q.draw]).replace(/<br>/g, ' ')}*`); return; }
    const a = typeof q.choices[0] === 'string' ? q.choices[0] : 'the first drawing (' + (q.choices[0].rule ? 'its arrow starts on the carbocation' : '') + ')';
    w(`- **${q.id}** ${q.q} *${a}* ${q.why}`);
  });
  w();
}
process.stdout.write(out.join('\n') + '\n');

/* tools/answer-key.js: regenerates ANSWER_KEY.md from the live data.
 *
 *   node tools/answer-key.js > ANSWER_KEY.md
 *
 * Every answer here is computed by the same model the activity uses, so the
 * key cannot disagree with what students see.
 */
const fs = require('fs');
const path = require('path');

global.window = { addEventListener() {}, matchMedia() { return { matches: false }; } };
global.document = { addEventListener() {} };
global.localStorage = { getItem() { return null; }, setItem() {}, removeItem() {} };
const src = path.join(__dirname, '..', 'src', 'js');
for (const f of ['geom.js', 'mol.js', 'name.js', 'layout.js', 'chair.js', 'draw.js', 'react.js', 'build3d.js', 'viewer3d.js', 'anim.js',
                 'mech.js', 'arrows.js', 'molecules.js', 'picker.js', 'quiz.js', 'scorm.js', 'app.js', 'steps1.js', 'steps2.js', 'steps3.js']) {
  (0, eval)(fs.readFileSync(path.join(src, f), 'utf8'));
}

const out = [];
const P = (s = '') => out.push(s);
const name = (m) => molName(m);
const FN = React.FUNCTIONS;

function figText(f) {
  if (typeof f === 'string') return f;
  if (f.pair) return f.pair.map(figText).join(' and ');
  if (f.rxn) return name(mol(f.rxn[0])) + ' + ' + React.REAGENTS[f.rxn[1]].text;
  if (f.mech) return 'curved arrows: ' + (f.label || f.arrows);
  if (f.mol) return name(mol(f.mol));
  if (f.smiles) return name(Mol.parse(f.smiles));
  if (f.ring) return name(Mol.fromRing(f.ring, f.ene));
  if (f.text) return f.text;
  return '?';
}

function products(id, key) {
  const r = React.predict(mol(id), key);
  return { r, list: r.products.map((p) => `${p.name} (${p.mech}, ${p.role}${p.regio ? ', ' + p.regio : ''})`) };
}

P('# Answer key: SN1, SN2, E1 and E2');
P();
P('Generated by `node tools/answer-key.js > ANSWER_KEY.md`.');
P('Do not edit by hand: change the data in `src/js/` and regenerate.');
P();
P(`${App.STEPS.length} steps; ${App.GRADED} graded questions in five checkpoints. Only the checkpoints are graded.`);
P();

P('## The function of each reagent (step 2)');
P();
P('| Reagent | Function | Why |');
P('| --- | --- | --- |');
React.REAGENT_ORDER.forEach((k) => { const r = React.REAGENTS[k]; P(`| ${r.text} | ${FN[r.fn].short}${FN[r.fn].klein ? ' (' + FN[r.fn].klein + ')' : ''} | ${r.why} |`); });
P();

P('## Klein’s decision table (step 23)');
P();
P('| Substrate | ' + React.FN_ORDER.map((f) => FN[f].short).join(' | ') + ' |');
P('| --- | --- | --- | --- | --- |');
[1, 2, 3].forEach((d) => P(`| ${d}° | ` + React.FN_ORDER.map((f) => App.resultOf(React.TABLE[d][f])).join(' | ') + ' |'));
P();
P('t-BuOK is a strong nucleophile and a strong base, but sterically hindered: at a 1° carbon it gives E2, some SN2; everywhere it gives the Hofmann product.');
P();

P('## The steps');
P();
App.STEPS.forEach((s, i) => {
  if (s.kind === 'quiz' || s.kind === 'results') return;
  P(`### ${i + 1}. ${s.title}`);
  P();
  if (s.mols) P('Molecules: ' + s.mols.map((id) => name(mol(id))).join('; ') + '.');
  if (s.mol) P('Molecule: ' + name(mol(s.mol)) + '.');
  if (s.kind === 'players') {
    s.mols.forEach((id) => {
      const m = mol(id), L = React.lg(m), num = Name.numbers(m);
      const b = React.betas(m, L.a).map((x) => App.U.carbonName(m, x.b));
      P(`- ${name(m)}: α carbon C${num[L.a]}; β carbons ${b.length ? b.join(', ') : 'none'}; ${React.DEGREE_WORD[Mol.degree(m, L.a)]}.`);
    });
  }
  if (s.kind === 'newman') {
    (s.mols || [s.mol]).forEach((id) => {
      const m = mol(id), L = React.lg(m);
      React.betas(m, L.a).forEach((b) => {
        const ps = React.e2From(m, L.a, b.b, L.x);
        if (ps.length) P(`- ${name(m)}, H from ${App.U.carbonName(m, b.b)}: ` + ps.map((p) => `${Name.name(p.mol)} (${p.how})`).join(', '));
      });
    });
  }
  if (s.kind === 'regio') s.mols.forEach((id) => {
    P(`- ${name(mol(id))} + NaOEt: ` + products(id, 'NaOEt').list.join('; '));
    P(`- ${name(mol(id))} + t-BuOK: ` + products(id, 'tBuOK').list.join('; '));
  });
  if (s.kind === 'ringregio' || s.kind === 'locked') s.mols.forEach((id) => {
    const c = React.chairs(mol(id));
    P(`- ${name(mol(id))}: the chair with the leaving group axial is ${c.gap <= 0 ? 'the more stable chair' : 'the less stable chair'}${c.gap > 15 ? ' (locked: E2 drastically slower)' : ''}. NaOEt gives ` +
      products(id, 'NaOEt').list.filter((t) => /E2/.test(t)).join('; ') + '.');
  });
  if (s.kind === 'shift') s.mols.forEach((id) => {
    const cp = React.cationPath(mol(id));
    P(`- ${name(mol(id))}: ${cp.shift.kind === 'H' ? 'hydride' : 'methyl'} shift; major substitution product ` +
      React.sn1Products(mol(id), 'EtOH').list.map((p) => Name.name(p.mol)).join(', ') + '.');
  });
  if (s.kind === 'sortsel') App.SEL_CARDS.forEach((c) => P(`- ${name(mol(c.sub))} + ${React.REAGENTS[c.key].text}: ${c.bin.replace('sel', 'selective').replace('spec', 'specific').replace(/^regio/, 'regio').replace(/^stereo/, 'stereo')}`));
  if (s.kind === 'predict') s.problems.forEach(([id, key], n) => {
    const { r, list } = products(id, key);
    P(`- Problem ${n + 1}: ${name(mol(id))} + ${React.REAGENTS[key].text}. Function: ${FN[React.REAGENTS[key].fn].short}. ` +
      `Substrate ${React.DEGREE_WORD[r.deg]}: ${App.resultOf(r.mechs)}. Products: ${list.join('; ')}.`);
  });
  const keys = { players: ['bond'], sortfn: ['base'], backside: ['backside', 'ringsn2'], sterics: ['fastest'], sn1stereo: ['flat'], shift: ['shift'],
                 e1: ['e1major'], ringanti: ['ringanti'], locked: ['locked', 'k718'] };
  if (s.kind === 'newman') keys.newman = { anti: ['anti'], selective: ['selective'], specific: ['specific'] }[s.mode];
  (keys[s.kind] || []).forEach((k) => { const p = App.PREDICT[k]; P(`- Prediction: ${p.q} **${p.choices[p.answer]}**`); });
  P();
});

P('## Checkpoints');
P();
Object.keys(QUIZZES).forEach((k) => {
  const Q = QUIZZES[k];
  P(`### ${Q.title}`);
  P();
  P(`Draws ${Q.draw} of ${Q.pool.length}; always asks: ${Q.core.join(', ')}.`);
  P();
  Q.pool.forEach((q) => {
    P(`- **${q.id}**: ${q.q}${q.fig ? ' [' + figText(q.fig) + ']' : ''}`);
    P(`  - Answer: **${figText(q.choices[0])}**`);
    P(`  - Other choices: ${q.choices.slice(1).map(figText).join('; ')}`);
    P(`  - Why: ${q.why}`);
  });
  P();
});

process.stdout.write(out.join('\n') + '\n');

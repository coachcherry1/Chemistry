/* ---------------------------------------------------------------- quiz */

P('## Checkpoint questions (graded)');
P();
P('★ = core question, asked in every attempt. The others are drawn at random to make up the checkpoint. The correct ' +
  'answer is listed first; on screen the choices are shuffled. Question ids are the SCORM interaction ids.');
P();
for (const k of Object.keys(QUIZZES)) {
  const Q = QUIZZES[k];
  P(`### ${Q.title} (${Q.draw} of ${Q.pool.length})`);
  P();
  for (const q of Q.pool) {
    P(`**${Q.core.indexOf(q.id) >= 0 ? '★ ' : ''}\`${q.id}\`** ${q.q}`);
    P();
    if (q.fig) P(`Figure: ${figText(q.fig)}.`);
    if (q.fig) P();
    q.choices.forEach((c, i) => P(`${i === 0 ? '- ✓ ' : '- '}${typeof c === 'string' ? c : figText(c)}`));
    P();
    P(`> ${q.why}`);
    P();
  }
}


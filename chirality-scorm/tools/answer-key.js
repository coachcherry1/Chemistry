const out = [];
const P = (s = '') => out.push(s);
const mol = (id) => molecule(id);
const order = (m, c) => CIP.rank(m, c).order;
const pri = (m, c) => order(m, c).map((j) => CIP.groupText(m, c, j)).join(' > ');
const cfg = (m) => App.configText(m) || 'no chirality centre';
const SLOT = { ul: 'upper left, in the page', ur: 'upper right, in the page', ll: 'lower left, in the page',
               lr: 'lower right, in the page', w: 'wedge', d: 'dash' };
const four = (m, c) => (STEREO.fourOnDash(m, c) ? '4 on the dash' : '4 ' + ({ wedge: 'on a wedge', plain: 'in the page' })[
  STEREO.bondStyle(m.atoms[c].p, m.atoms[order(m, c)[3]].p)]);

function drawing(m) {
  if (m.kind === 'ring') {
    return Object.keys(m.spec.ring).map((c) => ['t', 'b'].filter((f) => m.spec.ring[c][f]).map((f) =>
      `${GROUPS[m.spec.ring[c][f]].label} on C${c} (${f === 't' ? 'wedge' : 'dash'})`).join(', ')).join(', ');
  }
  if (m.kind === 'centre') {
    const a = STEREO.arrangement(m);
    return Object.keys(a).map((s) => `${GROUPS[a[s]].label} ${SLOT[s]}`).join(', ');
  }
  const L = Draw.layout(m, { showH: 'all' });
  return m.backbone.map((i) => {
    const bits = Object.keys(L.groups).filter((j) => L.groups[j].a === i && !L.groups[j].end && !m.atoms[j].terminal).map((j) => {
      const b = L.groups[j], g = m.atoms[j].group;
      return `${g ? GROUPS[g].label : m.atoms[j].el} (${b.style === 'plain' ? 'plain' : b.style})`;
    });
    return bits.length ? `C${m.atoms[i].num}: ${bits.join(', ')}` : null;
  }).filter(Boolean).join('; ');
}

function figText(f) {
  if (f.pair) return f.pair.map(figText).join(' | beside it: ');
  if (f.flat) return `flat drawing of ${mol(f.flat).name}`;
  if (f.newman) return `Newman projection of ${mol(f.newman).name}`;
  const m = App.figModel(f);
  const how = [f.mirror ? `mirror image (mirror ${f.mirror})` : '', f.turn != null ? `turned (${f.turn})` : ''].filter(Boolean).join(', ');
  return `${m.name}${how ? ', ' + how : ''}: ${drawing(m)} = ${cfg(m)}`;
}

P('# Answer key: Chirality, R and S, enantiomers, diastereomers and meso compounds');
P();
P('Generated by `node tools/answer-key.js > ANSWER_KEY.md`.');

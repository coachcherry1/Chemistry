for (const id of Object.keys(MOLECULES)) {
  const m = mol(id), cs = CIP.centres(m);
  const p = cs.map((c) => (m.kind === 'centre' ? '' : 'C' + m.atoms[c].num + ': ') + pri(m, c) + ` (${four(m, c)})`).join('<br>');
  const extra = STEREO.meso(m) ? ' (meso)' : cs.length && !STEREO.chiral(m) ? ' (achiral)' : !cs.length ? (STEREO.chiral(m) ? '' : ', achiral') : '';
  P(`| ${m.name} (\`${id}\`) | ${drawing(m)} | ${p || 'none'} | ${cfg(m)}${extra} |`);
}
P();

/* ---------------------------------------------------------------- steps */

P('## Steps (never graded)');
P();
const S = (id) => App.STEPS.find((s) => s.id === id);
const pk = (k) => App.PREDICT[k].choices[App.PREDICT[k].answer];
P('### Mirror, mirror');
P();
P(`Predictions: CHBrClF's mirror image fits? **${pk('fit1')}**. CH₂BrCl's? **${pk('fit2')}**. CHBrClF: at most 2 of 4 atoms ` +
  'ever line up. CH₂BrCl: all 4 line up after **Turn it over** on the image; its mirror plane is the page (through Br, C and Cl).');
P();
P('### Draw the mirror image');
P();
{
  const m = mol(S('drawmirror').mol);
  for (const w of ['beside', 'behind']) {
    const a = STEREO.arrangement(STEREO.mirror(m, w));
    P(`Mirror ${w === 'beside' ? 'beside the molecule' : 'behind the page'}: ` + Object.keys(a).map((s) => `${GROUPS[a[s]].label} ${SLOT[s]}`).join(', ') + '.');
    P();
  }
  P('The mirror-image template is drawn with its wedge on the right, so the right answer looks exactly like the reflection.');
  P();
}
P('### Find the chirality centres');
P();
for (const id of S('centres').mols) {
  const m = mol(id);
  const cs = CIP.centres(m).map((c) => 'C' + m.atoms[c].num);
  P(`- ${m.name}: **${cs.length ? cs.join(' and ') : 'none'}**`);
}
P();
P('### Priorities');
P();
P(`Predictions: priority 1 of CHBrClF is **${pk('top')}**; CH₂OH against C(CH₃)₃: **${pk('bigger')}**.`);
P();
for (const id of S('rank').mols.concat(S('ties').mols)) {
  const m = mol(id), o = order(m, m.centre);
  P(`- **${m.name}**: ${pri(m, m.centre)}.`);
  for (let k = 0; k < 3; k++) P(`  - ${k + 1} over ${k + 2}: ${CIP.explain(m, m.centre, o[k], o[k + 1])}`);
}
P();
P('### R and S');
P();
for (const id of S('wheel').mols.concat(S('rotate').mols)) {
  const m = mol(id), c = CIP.centres(m)[0];
  P(`- ${m.name}: ${four(m, c)} as drawn; ${pri(m, c)}: **${CIP.label(m, c)}**.`);
}
P();
P(`Prediction (4 on the wedge): can it be read as drawn? **${pk('asis')}**.`);
P();
{
  const m = mol('butanol_hidden');
  P(`### The hidden H`);
  P();
  P(`The hidden H on C2 points **${pk('hiddenH').toLowerCase()}**. Redrawn with H on the dash, three drawings are accepted ` +
    '(the molecule turned over, and those two spun about the dash):');
  P();
  const tiles = ['OH', 'CH3', 'Et', 'H'], slots = MOLECULES.SLOT_ORDER.A;
  for (const perm of STEREO.permutations([0, 1, 2, 3])) {
    const got = {};
    slots.forEach((s, i) => { got[s] = tiles[perm[i]]; });
    if (App.judgeRedraw(m, got).ok) P('- ' + slots.map((s) => `${GROUPS[got[s]].label} ${SLOT[s]}`).join(', '));
  }
  P();
  P(`Moving only the H and the OH (OH wedge, H dash, CH₃ and CH₂CH₃ unmoved) draws the mirror image, and gets that feedback. ` +
    `The molecule is **(${CIP.label(m, m.carbonAt[2])})-2-butanol**.`);
  P();
}
P(`### Mirror images have opposite labels`);
P();
P(`(R)-2-butanol's mirror image (mirror behind the page, H now on the wedge) is **${pk('mirrorLabel')}**. Rotating the ` +
  'original never changes its label.');
P();
P('### Two centres, four stereoisomers');
P();
{
  const ms = S('four').mols.map(mol);
  const L = ['A', 'B', 'C', 'D'];
  P(`Prediction: **${pk('count4')}** stereoisomers. ` + ms.map((m, i) => `${L[i]} ${cfg(m)}`).join(', ') + '.');
  P();
  for (let i = 0; i < 4; i++) for (let j = i + 1; j < 4; j++) P(`- ${L[i]} and ${L[j]}: **${STEREO.relation(ms[i], ms[j])}**`);
  P();
}
P('### Meso: Molecules A and B again');
P();
P(`Prediction: **${pk('count3')}** stereoisomers. Molecule A is ${cfg(mol('dbb_A'))}, meso: its mirror image fits after ` +
  `**Upside down**, and its mirror plane appears when C3 is turned 180° (Br eclipsing Br). Molecule B is ${cfg(mol('dbb_B'))}, ` +
  'chiral; no turn of the C2–C3 bond gives it a mirror plane. A and B are diastereomers.');
P();
P('### Rings');
P();

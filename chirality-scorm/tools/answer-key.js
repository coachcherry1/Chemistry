P();
for (const id of S('rings').mols) {
  const m = mol(id), pl = STEREO.ringPlane(m);
  P(`- ${m.name}: **${App.ringAnswer(m)}**` + (pl ? ` (mirror plane through C${pl.through[0]} and C${pl.through[1]})` : ' (no mirror plane)'));
}

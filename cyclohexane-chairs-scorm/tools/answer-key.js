const fs = require('fs');
const path = require('path');

global.window = { addEventListener() {}, matchMedia() { return { matches: false }; } };
global.document = { addEventListener() {} };
global.localStorage = { getItem() { return null; }, setItem() {}, removeItem() {} };
const src = path.join(__dirname, '..', 'src', 'js');
for (const f of ['groups.js', 'chair.js', 'molecules.js', 'avalues.js', 'draw.js', 'quiz.js', 'scorm.js', 'app.js']) {
  (0, eval)(fs.readFileSync(path.join(src, f), 'utf8'));
}

const fmt = AVAL.fmt;
const out = [];
const P = (s = '') => out.push(s);
const ax = (pos, k) => CHAIR.isAxial(pos, k);
const name = (g) => GROUPS[g].label + (g === 'Hr' ? ' (red)' : g === 'Hb' ? ' (blue)' : '');
const where = (pos, k) => 'C' + CHAIR.carbonOf(pos) + ', ' + CHAIR.describe(pos, k);

function placed(m, k) {
  const gs = MOLECULES.groups(m);
  if (!gs.length) return 'all H';
  return gs.map((g) => `${name(g.g)} on ${where(g.pos, k)}`).join('; ');
}

function figText(f) {
  if (f.boat) return 'the boat, all twelve H atoms drawn';
  if (f.flat) return `flat drawing of ${molecule(f.flat).name}`;
  if (f.newman) return `Newman projection down C${f.bond[0]}–C${f.bond[1]} of chair ${(f.k || 0) + 1} of ${molecule(f.newman).name}`;
  if (f.klein) {
    const k = f.k || 0, L = Draw.kleinLayout(molecule(f.klein), k).pos;
    let t = `chair ${k + 1} of ${molecule(f.klein).name} as two Newman projections (down C1–C2 and C5–C4); ` +
      MOLECULES.groups(molecule(f.klein)).map((g) => `${name(g.g)} on C${g.c} at ${Draw.clock(L[g.pos].a)}`).join(', ');
    if (f.letters) t += '; lettered: ' + Object.keys(f.letters).map((p) => `${f.letters[p]} = H on ${where(p, k)}`).join('; ');
    return t;
  }
  if (f.chair) {
    const m = molecule(f.chair), k = f.k || 0;
    let t = `chair ${k + 1} of ${m.name}` + (MOLECULES.groups(m).length ? ` (${placed(m, k)})` : '');
    if (f.letters) t += '; lettered: ' + Object.keys(f.letters).map((p) => `${f.letters[p]} = H on ${where(p, k)}`).join('; ');
    return t;
  }
  return '';
}

P('# Answer key: Cyclohexane chairs, ring flips and axial crowding');
P();
P('Generated by `node tools/answer-key.js > ANSWER_KEY.md`.');
P('Do not edit by hand: change the data in `src/js/` and regenerate.');
P();
P('Every checkpoint question asks students to compare, rank, identify or explain. The A-value table is open ' +
  'beside checkpoints 3 and 4. Nothing has to be calculated.');
P();
P('Chair 1 is the chair each molecule is first shown in; chair 2 is the chair after one ring flip. "Top" and ' +
  '"bottom" are the two faces of the ring: in a flat drawing a wedge is the top face and a dash the bottom face.');
P();

/* ---------------------------------------------------------------- A-values */

P('## A-values');
P();
P('| Group | A-value (kJ/mol) | Each 1,3-diaxial interaction | Source |');
P('| --- | ---: | ---: | --- |');
for (const r of AVAL.ROWS) {
  P(`| ${AVAL.NAMES[r[0]]} | ${fmt(r[1])} | ${AVAL.NAMES[r[0]]}/H ${fmt(r[1] / 2)} | ${AVAL.SOURCES[r[2]]} |`);
}
for (const p of AVAL.PAIRS) {
  P(`| two axial ${AVAL.NAMES[p[0]]} on one face | | ${AVAL.NAMES[p[0]]}/${AVAL.NAMES[p[1]]} ${fmt(p[2])} | ${AVAL.SOURCES[p[3]]} |`);
}
P();
P('A chair\'s energy is the sum of its 1,3-diaxial interactions. Shares of molecules are Boltzmann ratios at 25 °C.');
P();

/* ---------------------------------------------------------------- positions */

P('## Every position in both chairs');
P();
P('| Carbon | Top face, chair 1 | Bottom face, chair 1 | Top face, chair 2 | Bottom face, chair 2 |');
P('| --- | --- | --- | --- | --- |');
for (let c = 1; c <= 6; c++) {
  const d = (p, k) => ax(p, k) ? 'axial, up' : 'equatorial, slightly up';
  const e = (p, k) => ax(p, k) ? 'axial, down' : 'equatorial, slightly down';
  P(`| C${c} | ${d(c + 't', 0)} | ${e(c + 'b', 0)} | ${d(c + 't', 1)} | ${e(c + 'b', 1)} |`);
}
P();
P('A ring flip swaps axial and equatorial at every position; no position changes face. An axial group on C1 ' +
  'crowds the axial positions on C3 and C5 (same face): the 1,3-diaxial interactions.');
P();

/* ---------------------------------------------------------------- molecules */

P('## Molecules');
P();
P('| Molecule | Chair 1 | Chair 2 | More stable | Share at any moment |');
P('| --- | --- | --- | --- | --- |');
for (const id of Object.keys(MOLECULES)) {
  if (id === 'tracked') continue;
  const m = molecule(id), b = AVAL.better(m);
  const cell = (k) => `${placed(m, k)}. ${AVAL.breakdown(m, k).replace(/\s+/g, ' ')}`;
  const share = b < 0 ? 'half in each chair' : `${AVAL.shareText(AVAL.share(m, b))} in chair ${b + 1}`;
  P(`| ${m.name} (\`${id}\`) | ${cell(0)} | ${cell(1)} | ${b < 0 ? 'equal' : 'chair ' + (b + 1)} | ${share} |`);
}
P();

/* ---------------------------------------------------------------- builds */

P('## Builds (never graded)');
P();
for (const s of App.STEPS.filter((x) => x.kind === 'build')) {
  const m = molecule(s.mol);
  P(`### ${s.title}: ${m.name}`);
  P();
  if (s.source === 'newman') {
    const K = [0, 1].map((k) => Draw.kleinLayout(m, k).pos);
    P('In Newman projections down C1–C2 and C5–C4 (C1 the front carbon on the right). Every bond on C1 turns 60° ' +
      'in the flip: ' + s.slots.map((p) => `${name(MOLECULES.groupAt(m, CHAIR.carbonOf(p), CHAIR.faceOf(p)))} from ` +
      `${Draw.clock(K[0][p].a)} to **${Draw.clock(K[1][p].a)}** (${CHAIR.describe(p, 1)})`).join('; ') + '.');
    P();
    continue;
  }
  P(s.source === 'flat'
    ? `From the flat drawing (${MOLECULES.groups(m).map((g) => `${name(g.g)} on C${g.c} on a ${g.f === 't' ? 'wedge' : 'dash'}`).join(', ')}) to chair ${s.k + 1}:`
    : `From chair 1 (${placed(m, 0)}) to chair 2:`);
  P();
  for (const p of s.slots) P(`- ${where(p, s.k)}: **${name(MOLECULES.groupAt(m, CHAIR.carbonOf(p), CHAIR.faceOf(p)))}**`);
  P();
}

/* ---------------------------------------------------------------- predictions */

P('## Predictions (never graded)');
P();
const PR = App.PREDICT;
const key = (p) => p.choices[p.answer];
P(`- **Meet the chair**: ${PR.flat.q} *${key(PR.flat)}.*`);
P(`- **Chair or boat?** ${PR.boat.q} *${key(PR.boat)}.* The boat has steric strain (flagpole H atoms 1t and 4t, ` +
  `${CHAIR.vec.dist(CHAIR.atom(CHAIR.model(molecule('cyclohexane'), 0.5), '1t').p, CHAIR.atom(CHAIR.model(molecule('cyclohexane'), 0.5), '4t').p).toFixed(2)} Å apart) ` +
  'and torsional strain (C2–C3 and C5–C6 eclipsed).');
P(`- **Up or down?** ${PR.axialC2.q} *${key(PR.axialC2)}.* ${PR.eqC1.q} *${key(PR.eqC1)}.*`);
P(`- **Flip the ring**: ${PR.flip.q} *${key(PR.flip)}.*`);
P(`- **Flip it equatorial**: ${PR.lower.q} *${key(PR.lower)}.* ${PR.count.q} *${key(PR.count)}.*`);
P(`- **Down the C1–C2 bond**: ${PR.gauche.q} *${key(PR.gauche)}.* ${PR.anti.q} *${key(PR.anti)}.*`);
P('- **Bigger groups push harder**: compared with CH₃, how strongly does the group prefer equatorial? ' +
  MOLECULES.SWAP_ORDER.map((x) => {
    const c = ['less strongly', 'a little more strongly', 'far more strongly'][App.swapAnswer(x)];
    return `${GROUPS[x].label}: *${c}* (A-value ${fmt(AVAL.aValue(x))}, ${AVAL.shareText(AVAL.share(molecule(MOLECULES.BY_GROUP[x]), 1))} equatorial)`;
  }).join('; ') + '.');
P('- **Which chair wins?** Flipping chair 1 to chair 2, the energy of trans-1,4-dimethylcyclohexane *goes down* ' +
  '(diaxial to diequatorial); that of cis-1,4-dimethylcyclohexane *stays the same*. ' +
  `${PR.cistrans.q} *${key(PR.cistrans)}.*`);
for (const b of App.BEST) {
  P(`- **Lock in the better chair**: ${b.q} *${b.choices[App.bestAnswer(b)]}* (chair ${AVAL.better(molecule(b.id)) + 1}).`);
}
P();

/* ---------------------------------------------------------------- quizzes */

P('## Checkpoint questions (graded)');
P();
P(`Each attempt draws ${Object.keys(QUIZZES).map((k) => QUIZZES[k].draw).join(' + ')} = ${App.GRADED} questions. ` +
  'Core questions (★) are always drawn; the rest of each checkpoint is filled at random from its pool. ' +
  'The first answer counts.');
P();
for (const k of Object.keys(QUIZZES)) {
  const Q = QUIZZES[k];
  P(`### ${Q.title} (${Q.draw} of ${Q.pool.length})`);
  P();
  Q.pool.forEach((q, i) => {
    const core = Q.core.includes(q.id) ? ' ★' : '';
    P(`${i + 1}. **${q.q}**${core} \`${q.id}\``);
    if (q.struct) P(`   - Shown: ${q.struct.map((id) => 'flat drawing of ' + molecule(id).name).join(', ')}`);
    if (q.fig) P(`   - Figure: ${figText(q.fig)}`);
    const ans = typeof q.choices[0] === 'string' ? q.choices[0] : figText(q.choices[0]);
    P(`   - Answer: ${ans}`);
    const wrong = q.choices.slice(1).map((c) => typeof c === 'string' ? c : figText(c));
    P(`   - Distractors: ${wrong.join(' · ')}`);
    P(`   - Explanation shown: ${q.why}`);
  });
  P();
}

process.stdout.write(out.join('\n') + '\n');

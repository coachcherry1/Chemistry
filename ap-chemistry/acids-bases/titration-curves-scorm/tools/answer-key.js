/* tools/answer-key.js: writes the answer key as Markdown.
 *
 *   node tools/answer-key.js > ANSWER_KEY.md
 *
 * Everything comes from the model (titration.js) and the item bank, so the
 * key cannot drift from what the activity marks right.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const src = path.join(__dirname, '..', 'src');
const ctx = {
  console, Math, JSON, Object, Array, String, Number, Error, isNaN, parseInt, Date, RegExp, URLSearchParams,
  window: { matchMedia: () => ({ matches: false }), addEventListener() {} },
  document: { addEventListener() {}, documentElement: {} },
  getComputedStyle: () => ({ getPropertyValue: () => '' })
};
vm.createContext(ctx);
const html = fs.readFileSync(path.join(src, 'index.html'), 'utf8');
[...html.matchAll(/<script src="([^"]+)"><\/script>/g)].forEach((m) => {
  vm.runInContext(fs.readFileSync(path.join(src, m[1]), 'utf8'), ctx, { filename: m[1] });
});
const { Titration: T, QUIZZES, App } = ctx;

const out = [];
const p = (s) => out.push(s == null ? '' : s);
const f2 = (x) => x.toFixed(2);

p('# Titration Curves, answer key');
p();
p('Generated by `node tools/answer-key.js` from the model and the item bank. Do not edit by hand.');
p();
p(`${App.STEPS.length} steps; ${App.GRADED} graded questions per attempt (five checkpoints of four). ★ marks a core question, asked in every ` +
  'attempt; the rest of each checkpoint is drawn at random from its pool. In the LMS, choice letters are recorded as a = the correct answer ' +
  'below, b, c, d = the others in the order listed (the screen shuffles them).');
p();

p('## The titrations');
p();
p('25.00 mL of 0.100 M acid in the flask, 0.100 M NaOH from the buret; 24 acid units are drawn, so one NaOH unit is 25/24 mL. ' +
  'The pH is solved exactly from a charge balance. Water is not drawn.');
p();
p('| Titration | Acid | Ka | pKa | pH at the start | Half-equivalence | Before equivalence | Equivalence | After equivalence |');
p('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
['SS', 'WS', 'AC'].forEach((sys) => {
  const S = T.SYSTEMS[sys];
  p(`| ${S.acid} with NaOH${sys === 'AC' ? ' (review only)' : ''} | ${S.weak ? 'weak' : 'strong'} | ${S.weak ? S.ka.toExponential(1) : 'very large'} | ` +
    `${S.weak ? f2(T.pKa(sys)) : '-'} | ` + T.POINTS.map((pt) => f2(T.pH(sys, pt.u))).join(' | ') + ' |');
});
p();
p('The five points: ' + T.POINTS.map((pt, i) => `${i + 1}. ${pt.name} (${pt.u} units, ${f2(T.volume(pt.u))} mL)`).join('; ') + '.');
p();
p('### What is drawn at each point');
p();
['SS', 'WS', 'AC'].forEach((sys) => {
  const S = T.SYSTEMS[sys];
  p(`**${S.acid} with NaOH** (${S.sym} and ${S.asym} in the diagram)`);
  p();
  p('| Point | ' + T.species(sys).map((x) => x.label).join(' | ') + ' | What decides the pH |');
  p('| --- | ' + T.species(sys).map(() => '---').join(' | ') + ' | --- |');
  T.POINTS.forEach((pt) => {
    const c = T.counts(sys, pt.u);
    p(`| ${pt.name} | ` + T.species(sys).map((x) => c[x.id]).join(' | ') + ` | ${T.setterChoice(sys, T.setter(sys, pt.u))} |`);
  });
  p();
});
p(`Notes: only about 8% of 0.100 M HF ionizes (2 of 24 units drawn); only about 1 in 75 acetic acid molecules ionizes, so none is drawn at the ` +
  `start. At the HF equivalence point only about 1 F⁻ in ${T.reactingOneIn('WS').toLocaleString('en-US')} reacts with water (about 1 in ` +
  `${T.reactingOneIn('AC').toLocaleString('en-US')} for acetic acid); the “why” step draws one as a sample and says so. Half-equivalence pH is ` +
  `${f2(T.pH('WS', 12))} for HF (pKa ${f2(T.pKa('WS'))}) and ${f2(T.pH('AC', 12))} for acetic acid (pKa ${f2(T.pKa('AC'))}).`);
p();

p('## Steps (not graded)');
p();
const walkAns = (sys) => T.POINTS.map((pt, k) => `   - Point ${k + 1}, ${pt.name}: flask **${T.flask(sys, pt.u)}**; the pH is decided by **${T.setterChoice(sys, T.setter(sys, pt.u))}** (pH ${f2(T.pH(sys, pt.u))}).`);
App.STEPS.forEach((s, k) => {
  p(`${k + 1}. **${s.title}** (\`${s.id}\`)`);
  if (s.id === 'setup') p('   - Predict: 25.00 mL of 0.100 M NaOH, because the moles of base must equal the moles of acid.');
  if (s.kind === 'walk') walkAns(s.sys).forEach(p);
  if (s.id === 'compare') p(`   - Predict: the HCl flask has more H⁺ (24, against ${T.counts('WS', 0).H} in the HF flask). pH ${f2(T.pH('SS', 0))} against ${f2(T.pH('WS', 0))}.`);
  if (s.id === 'side') T.POINTS.forEach((pt) => p(`   - ${pt.name}: HCl ${T.flask('SS', pt.u)} (pH ${f2(T.pH('SS', pt.u))}); HF ${T.flask('WS', pt.u)} (pH ${f2(T.pH('WS', pt.u))}).`));
  if (s.id === 'why') {
    p('   - HCl flask: no particle decides the pH (Na⁺ and Cl⁻ do not react with water): pH 7.');
    p(`   - HF flask: **F⁻** decides it (F⁻ + H₂O → HF + OH⁻): pH ${f2(T.pH('WS', 24))}.`);
  }
  if (s.id === 'pairs') {
    p('   - Exactly 7: ' + T.PAIRS.filter((x) => T.pairSide(x) === 'equal').map((x) => `${x.acid} + ${x.base}`).join(', ') + '.');
    p('   - Above 7: ' + T.PAIRS.filter((x) => T.pairSide(x) === 'above').map((x) => `${x.acid} + ${x.base}`).join(', ') + '.');
  }
  if (s.id === 'match') T.POINTS.forEach((pt, i) => p(`   - ${i + 1}. ${pt.name}: ${T.flask('WS', pt.u)}.`));
  if (s.id === 'find') {
    p('   - The weak acid (HF) is the curve that starts higher; its letter is random for each student.');
    p(`   - Half-equivalence point of HF: ${f2(T.volume(12))} mL (pH ${f2(T.pH('WS', 12))}). Equivalence point of HF and of HCl: ${f2(T.volume(24))} mL. The marker is accepted within one unit (about 1 mL).`);
  }
});
p();

p('## Checkpoints (graded)');
p();
Object.keys(QUIZZES).forEach((k) => {
  const Q = QUIZZES[k];
  p(`### ${Q.title}`);
  p();
  p(`${Q.draw} questions are drawn from a pool of ${Q.pool.length}.`);
  p();
  Q.pool.forEach((q) => {
    const fig = q.diagram ? ` *(diagram: ${T.SYSTEMS[q.diagram.sys].acid} flask, ${q.diagram.u} units of NaOH)*`
      : (q.curve ? ` *(curve: ${q.curve.systems.map((c) => T.SYSTEMS[c.sys].acid + (c.label ? ' as ' + c.label : '')).join(' and ')}${q.curve.mark != null ? ', dot at ' + q.curve.mark + ' units' : ''})*` : '');
    p(`- ${Q.core.indexOf(q.id) >= 0 ? '★ ' : ''}\`${q.id}\` ${q.q}${fig}`);
    p(`  - **a. ${q.choices[0]}**`);
    q.choices.slice(1).forEach((c, i) => p(`  - ${String.fromCharCode(98 + i)}. ${c}`));
    p(`  - Why: ${q.why}`);
  });
  p();
});

process.stdout.write(out.join('\n') + '\n');

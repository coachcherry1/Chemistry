/* tools/answer-key.js: writes the answer key as Markdown.
 *
 *   node tools/answer-key.js > ANSWER_KEY.md
 *
 * Everything comes from the model (buffer.js) and the item bank, so the
 * key cannot drift from what the activity marks right.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const src = path.join(__dirname, '..', 'src');
const ctx = {
  console, Math, JSON, Object, Array, String, Number, Error, isNaN, parseInt, Date, RegExp, URLSearchParams, Set,
  window: { matchMedia: () => ({ matches: false }), addEventListener() {} },
  document: { addEventListener() {}, documentElement: {} },
  getComputedStyle: () => ({ getPropertyValue: () => '' })
};
vm.createContext(ctx);
const html = fs.readFileSync(path.join(src, 'index.html'), 'utf8');
[...html.matchAll(/<script src="([^"]+)"><\/script>/g)].forEach((m) => {
  vm.runInContext(fs.readFileSync(path.join(src, m[1]), 'utf8'), ctx, { filename: m[1] });
});
const { Buf: B, QUIZZES, App } = ctx;

const out = [];
const p = (s) => out.push(s == null ? '' : s);
const f2 = (x) => x.toFixed(2);

p('# Buffers, answer key');
p();
p('Generated by `node tools/answer-key.js` from the model and the item bank. Do not edit by hand.');
p();
p(`${App.STEPS.length} steps; ${App.GRADED} graded questions per attempt (five checkpoints of four). ★ marks a core question, asked in every ` +
  'attempt; the rest of each checkpoint is drawn at random from its pool. In the LMS, choice letters are recorded as a = the correct answer ' +
  'below, b, c, d = the others in the order listed (the screen shuffles them).');
p();

p('## The model');
p();
p('One particle stands for 0.010 M. The buffer starts with 10 acid-member and 10 base-member particles. A flask also records how much strong acid (HCl) ' +
  'or strong base (NaOH) has been added, in the same units (dilution ignored). The pH is solved exactly from a charge balance; water is not drawn.');
p();
p(`pKa: acetic acid ${f2(B.pKa('AC'))} (Ka 1.8 × 10⁻⁵); NH₄⁺ ${f2(B.pKa('NH'))} (from Kb of NH₃ 1.8 × 10⁻⁵).`);
p();
p('| HCl added (+) or NaOH added (−) | Buffer pH (HAc / Ac⁻) | Pure water | HAc alone | Buffer pH (NH₄⁺ / NH₃) | Flask (acetate buffer) |');
p('| --- | --- | --- | --- | --- | --- |');
[-12, -10, -8, -4, 0, 4, 8, 10, 12].forEach((x) => {
  p(`| ${x > 0 ? '+' + x : x} | ${f2(B.pH('AC', 10, 10, x))} | ${f2(B.pHWater(x))} | ${f2(B.pH('AC', 10, 0, x))} | ${f2(B.pH('NH', 10, 10, x))} | ${B.flaskList('AC', 10, 10, x)} |`);
});
p();
p('The buffer works while both members are present. With 10 of each, the base member is gone after 10 particles of acid and the acid member after 10 of base, ' +
  'and the pH then changes sharply (the "cliffs" in the range steps).');
p();
p('**The equation** pH = pKa + log([base member] / [acid member]) agrees with the exact pH to within 0.02 for every buffer the activity draws. It is shown only with ' +
  'the warning that it is for a buffer with appreciable amounts of both members. In the activity "appreciable" means neither member is less than a tenth of the other.');
p();

p('## Steps (not graded)');
p();
App.STEPS.forEach((s, k) => {
  p(`${k + 1}. **${s.title}** (\`${s.id}\`)`);
  if (s.id === 'problem') p(`   - Predict: the pure water changes much more (pH ${f2(B.pHWater(0))} to ${f2(B.pHWater(4))}) than the buffer (${f2(B.pH('AC', 10, 10, 0))} to ${f2(B.pH('AC', 10, 10, 4))}) when 4 HCl are added.`);
  if (s.id === 'members') p('   - Acid member and base member differ by one H⁺. Switch between acetic acid / acetate (Na⁺ spectator) and ammonium / ammonia (Cl⁻ spectator).');
  if (s.id === 'sort') {
    p('   - Could be a buffer: CH₃COOH + CH₃COONa, NH₃ + NH₄Cl, HF + NaF, HCN + KCN.');
    p('   - Not a buffer: HCl + NaCl, CH₃COOH + NaCl, NaOH + NaCl, NH₃ + NaOH.');
  }
  if (s.kind === 'walk') {
    const sign = s.dir === 'acid' ? 1 : -1;
    p(`   - Point 1: the particle that reacts is ${s.dir === 'acid' ? 'Ac⁻ (H⁺ + Ac⁻ → HAc)' : 'HAc (OH⁻ + HAc → Ac⁻ + H₂O)'}.`);
    [2, 4, 6, 8].forEach((n, i) => p(`   - Point ${i + 2}, ${n} ${s.dir === 'acid' ? 'HCl' : 'NaOH'}: **${B.flaskList('AC', 10, 10, n * sign)}**; buffer pH ${f2(B.pH('AC', 10, 10, n * sign))}, pure water pH ${f2(B.pHWater(n * sign))}.`));
  }
  if (s.kind === 'click') p(`   - Click **${s.dir === 'acid' ? 'Ac⁻' : 'HAc'}**; each wrong particle has its own reason.`);
  if (s.id === 'range') p('   - Predict: the base member takes added acid and the acid member takes added base, so the ratio hardly changes. Then reach 11 or more particles of acid and of base.');
  if (s.id === 'ratio') {
    p(`   - Equal amounts (11 and 11): pH ${f2(B.pH('AC', 11, 11, 0))} = pKa. Ratio 10 (20 Ac⁻, 2 HAc): pH ${f2(B.pH('AC', 2, 20, 0))}. Reach 2 or 3 and 19 or 20 Ac⁻ to finish.`);
  }
  if (s.id === 'when') {
    p('   - Works: 10 HAc + 10 Ac⁻; 14 HAc + 6 Ac⁻; 8 NH₄⁺ + 12 NH₃.');
    p('   - Does not work: HAc alone; Ac⁻ alone; HCl in water.');
  }
  if (s.id === 'use') {
    const a1 = B.after(10, 10, 4), a2 = B.after(10, 10, -3);
    p(`   - 4 HCl: ${a1.ha} HAc and ${a1.a} Ac⁻, pH ${f2(B.hh('AC', a1.ha, a1.a))}.`);
    p(`   - 3 NaOH: ${a2.ha} HAc and ${a2.a} Ac⁻, pH ${f2(B.hh('AC', a2.ha, a2.a))}.`);
  }
  if (s.id === 'base-buffer') p(`   - NH₃ takes added H⁺ (H⁺ + NH₃ → NH₄⁺). Buffer pH ${f2(B.pH('NH', 10, 10, 0))} at the start.`);
});
p();

p('## Checkpoints (graded)');
p();
Object.keys(QUIZZES).forEach((k) => {
  const Q = QUIZZES[k];
  p(`### ${Q.title}`);
  p();
  p(`${Q.draw} questions are drawn from a pool of ${Q.pool.length}.`);
  p();
  Q.pool.forEach((q) => {
    const fig = q.diagram ? ` *(diagram: ${q.diagram.ha} ${B.PAIRS[q.diagram.pair].ha}, ${q.diagram.a} ${B.PAIRS[q.diagram.pair].a}, ${q.diagram.x === 0 ? 'nothing added' : (q.diagram.x > 0 ? q.diagram.x + ' HCl' : -q.diagram.x + ' NaOH') + ' added'})*`
      : (q.curve ? ' *(graph: buffer A and pure water B)*' : '');
    p(`- ${Q.core.indexOf(q.id) >= 0 ? '★ ' : ''}\`${q.id}\` ${q.q}${fig}`);
    p(`  - **a. ${q.choices[0]}**`);
    q.choices.slice(1).forEach((c, i) => p(`  - ${String.fromCharCode(98 + i)}. ${c}`));
    p(`  - Why: ${q.why}`);
  });
  p();
});

process.stdout.write(out.join('\n') + '\n');
